  bool initializePersistentSolidParticleOwner(
      bool capture_legacy_topology = false) {
#ifdef ENABLE_CUDA_STAGE2_PROBE
    if constexpr (dim == 3) {
      const char* solid_owner_env =
          std::getenv("ZIRAN_GPU_SOLID_PARTICLE_OWNER");
      const bool solid_owner_enabled =
          solid_owner_env == nullptr || std::atoi(solid_owner_env) != 0;
      const bool solid_owner_supported = gpu_build_system &&
          solid_owner_enabled &&
          Base::config_scheme == CONFIG_TOTAL_LAGRANGIAN &&
          Base::transfer_scheme == Base::APIC_blend_RPIC;
      if (!solid_owner_supported) {
        GPU_STAGE3A::invalidatePersistentSolidParticleState3D(
            gpu_solid_particle_state);
        gpu_solid_p2g_node_map = {};
        gpu_solid_p2g_indices_ready = false;
        gpu_solid_legacy_q2_topology_seed.clear();
        gpu_solid_device_grid_active = false;
        return false;
      }
      if (GPU_STAGE3A::persistentSolidParticleStateValid(
              gpu_solid_particle_state,
              static_cast<std::size_t>(particles.count)))
        return true;

      auto* F_pointer = particles.DataManager::getPointer(F_name<T, dim>());
      auto* J_pointer = particles.DataManager::getPointer(J_name<T>());
      auto* X0_pointer = particles.DataManager::getPointer(X0_name<TV>());
      auto* C_pointer = particles.DataManager::getPointer(C_name<TM>());
      auto* vol_pointer =
          particles.DataManager::getPointer(element_measure_name<T>());
      auto* j_model = particles.DataManager::getPointer(
          MaterialForce::j_constitutive_model_name());
      ZIRAN_ASSERT(F_pointer && J_pointer && X0_pointer && C_pointer &&
                       vol_pointer && j_model,
                   "solid particle owner requires F/J/X0/C/volume/model "
                   "attributes");

      GPU_STAGE3A::SolidParticleStateInput3D state_input;
      const std::size_t count = static_cast<std::size_t>(particles.count);
      state_input.rest_x.resize(count);
      state_input.current_x.resize(count);
      state_input.velocity.resize(count);
      state_input.affine.resize(count);
      state_input.grad_velocity.resize(count);
      state_input.f.resize(count);
      state_input.j.resize(count);
      state_input.mass.resize(count);
      state_input.volume.resize(count);
      state_input.lambda.resize(count);
      const bool has_grad_velocity =
          Base::scratch_gradV.size() == count;
      tbb::parallel_for(0, particles.count, [&](int i) {
        const std::size_t p = static_cast<std::size_t>(i);
        auto pack_vec = [](const TV& value) {
          return GPU_STAGE3A::Vec3d{static_cast<double>(value[0]),
              static_cast<double>(value[1]), static_cast<double>(value[2])};
        };
        auto pack_mat = [](const TM& value) {
          GPU_STAGE3A::Mat3d result;
          for (int row = 0; row < 3; ++row)
            for (int col = 0; col < 3; ++col)
              result.values[row * 3 + col] =
                  static_cast<double>(value(row, col));
          return result;
        };
        state_input.rest_x[p] = pack_vec(particles.X.array[i]);
        state_input.current_x[p] = pack_vec((*X0_pointer)[i]);
        state_input.velocity[p] = pack_vec(particles.V.array[i]);
        state_input.affine[p] = pack_mat((*C_pointer)[i]);
        state_input.grad_velocity[p] = has_grad_velocity
            ? pack_mat(Base::scratch_gradV[i]) : GPU_STAGE3A::Mat3d{};
        state_input.f[p] = pack_mat((*F_pointer)[i]);
        state_input.j[p] = static_cast<double>((*J_pointer)[i]);
        state_input.mass[p] = static_cast<double>(particles.mass.array[i]);
        state_input.volume[p] = static_cast<double>((*vol_pointer)[i]);
        state_input.lambda[p] = static_cast<double>((*j_model)[i].lambda);
      });
      GPU_STAGE3A::SolidParticleStateStats owner_stats;
      GPU_STAGE3A::initializePersistentSolidParticleState3D(
          gpu_solid_particle_state, state_input, &owner_stats);
      gpu_solid_p2g_node_map = {};
      gpu_solid_p2g_indices_ready = false;
      gpu_solid_legacy_q2_topology_seed.clear();
      if (capture_legacy_topology) {
        gpu_solid_legacy_q2_topology_seed.reserve(
            static_cast<std::size_t>(grid.getNumNodes()));
        grid.iterateGridSerial([&](IV node, GridState<T, dim>& g) {
          GPU_STAGE3A::AssemblyGridNode entry;
          entry.key = GPU_STAGE3A::packGridKey3D(
              node[0], node[1], node[2]);
          entry.idx = g.idx;
          entry.mass = static_cast<double>(g.m);
          entry.new_v = {static_cast<double>(g.new_v[0]),
              static_cast<double>(g.new_v[1]),
              static_cast<double>(g.new_v[2])};
          entry.v = {static_cast<double>(g.v[0]),
              static_cast<double>(g.v[1]),
              static_cast<double>(g.v[2])};
          gpu_solid_legacy_q2_topology_seed.push_back(entry);
        });
      }
      gpu_solid_device_grid_active = false;
      gpu_solid_host_current_x_valid = true;
      gpu_solid_host_dynamic_state_valid = true;
      ZIRAN_INFO("GPU solid particle owner initialize: particles=",
          owner_stats.particles, " legacy_q2_seed_nodes=",
          gpu_solid_legacy_q2_topology_seed.size(), " upload_ms=",
          owner_stats.upload_ms);
      return true;
    }
#endif
    return false;
  }

  bool canUseResidentSolidDeviceGrid() {
#ifdef ENABLE_CUDA_STAGE2_PROBE
    if constexpr (dim == 3) {
      if (category != MATERIAL_PHASE_SOLID || !gpu_solid_device_resident ||
          !gpu_solid_implicit_state || !gpu_solid_implicit_pcg ||
          gpu_solid_implicit_probe || Base::diff_test ||
          Base::symplectic || !solid_Q2Q0 ||
          Base::config_scheme != CONFIG_TOTAL_LAGRANGIAN ||
          Base::transfer_scheme != Base::APIC_blend_RPIC || !Base::force ||
          !Base::force->material_force ||
          (Base::force->multi_target_pinning &&
           !Base::force->multi_target_pinning->collider_spring) ||
          std::getenv("ZIRAN_SOLID_GPU_STATE_ORACLE") != nullptr ||
          std::getenv("ZIRAN_SOLID_GPU_PCG_ORACLE") != nullptr)
        return false;
      const bool has_pd = particles.exist(
          MaterialForce::template f_constitutive_model_name<PDIsotropic<T, dim>>());
      const bool has_corotated = particles.exist(
          MaterialForce::template f_constitutive_model_name<
              CorotatedIsotropic<T, dim>>());
      if (!has_pd && !has_corotated)
        return false;
      // The CUDA PD trial kernel includes the production TL self-contact
      // neighbor search, residual force and isotropic contact tangent.  Its
      // legacy contact energy is intentionally not used by example 1 (line
      // search is disabled), so retain the host fallback for line-searched or
      // Corotated TL-contact variants until their energy contract is covered.
      if (Base::force->lagrangian_contact &&
          (!has_pd || Base::newton.linesearch))
        return false;
      const bool ghost_contact = !Base::collision_objects.empty() &&
          has_corotated && canUseResidentSolidGhostContact();
      if (!Base::collision_objects.empty() && !ghost_contact)
        return false;
      if (Base::force->pinning && !canUseResidentSolidOrdinaryPinning())
        return false;
      return true;
    }
#endif
    return false;
  }

  void particlesToGrid() {
    ZIRAN_TIMER();
    if constexpr (dim == 3) {
      if (category == MATERIAL_PHASE_SOLID && gpu_solid_device_resident &&
          !GPU_STAGE3A::persistentSolidParticleStateValid(
              gpu_solid_particle_state,
              static_cast<std::size_t>(particles.count)))
        initializePersistentSolidParticleOwner(false);
      const bool resident_solid_p2g =
          category == MATERIAL_PHASE_SOLID && gpu_solid_device_resident &&
          !Base::symplectic && solid_Q2Q0 &&
          Base::config_scheme == CONFIG_TOTAL_LAGRANGIAN &&
          Base::transfer_scheme == Base::APIC_blend_RPIC &&
          GPU_STAGE3A::persistentSolidParticleStateValid(
              gpu_solid_particle_state,
              static_cast<std::size_t>(particles.count));
      if (category == MATERIAL_PHASE_SOLID && gpu_full_pipeline_strict) {
        ZIRAN_ASSERT(resident_solid_p2g,
            "strict full-GPU solid P2G fell back to CPU");
      }
      if (category == MATERIAL_PHASE_SOLID) {
        gpu_solid_final_grid_device_ready = false;
        gpu_solid_device_grid_active = false;
        if (!resident_solid_p2g) {
          gpu_solid_p2g_node_map = {};
          gpu_solid_p2g_indices_ready = false;
          gpu_solid_legacy_q2_topology_seed.clear();
        }
      }
      if (resident_solid_p2g) {
        const bool supports_device_grid = canUseResidentSolidDeviceGrid();
        if (gpu_full_pipeline_strict) {
          ZIRAN_ASSERT(supports_device_grid,
              "strict full-GPU solid device grid is unsupported");
        }
        const bool has_legacy_topology_seed =
            !gpu_solid_p2g_indices_ready &&
            !gpu_solid_legacy_q2_topology_seed.empty();
        const bool assign_canonical_topology = supports_device_grid &&
            !gpu_solid_p2g_indices_ready && !has_legacy_topology_seed;
        const bool request_device_grid = supports_device_grid &&
            (gpu_solid_p2g_indices_ready || has_legacy_topology_seed ||
             assign_canonical_topology);
        std::vector<GPU_STAGE3A::AssemblyGridNode> nodes;
        GPU_STAGE3A::SolidVelocityGridStats stats;
        GPU_STAGE3A::buildPersistentSolidVelocityGridQ2ToHost(
            gpu_solid_particle_state, static_cast<double>(Base::dx), nodes,
            &stats, !request_device_grid,
            has_legacy_topology_seed
                ? &gpu_solid_legacy_q2_topology_seed
                : nullptr,
            assign_canonical_topology);
        gpu_solid_device_grid_active =
            request_device_grid &&
            (stats.reused_static_topology ||
             stats.assigned_canonical_topology);
        if (gpu_full_pipeline_strict) {
          ZIRAN_ASSERT(gpu_solid_device_grid_active,
              "strict full-GPU solid Q2 topology fell back to host");
        }
        if (!gpu_solid_device_grid_active) {
          for (const auto& entry : nodes) {
            int x, y, z;
            GPU_STAGE2::unpackGridKey3D(entry.key, x, y, z);
            GridState<T, dim>& g = grid[IV(x, y, z)];
            g.m = static_cast<T>(entry.mass);
            g.v = TV(static_cast<T>(entry.v.x), static_cast<T>(entry.v.y),
                     static_cast<T>(entry.v.z));
          }
        }
        if (gpu_solid_device_grid_active) {
          Base::num_nodes = static_cast<int>(stats.nodes);
        } else {
          Base::num_nodes = grid.getNumNodes();
          ZIRAN_ASSERT(Base::num_nodes == static_cast<int>(nodes.size()),
                       "resident solid Q2 P2G topology mismatch");
        }
        gpu_solid_p2g_node_map =
            GPU_STAGE3A::getPersistentSolidVelocityGridQ2DeviceMap(
                gpu_solid_particle_state);
        const std::size_t expected_device_nodes =
            gpu_solid_device_grid_active ? stats.nodes : nodes.size();
        ZIRAN_ASSERT(gpu_solid_p2g_node_map.size == expected_device_nodes,
                     "resident solid Q2 device map size mismatch");
        if (gpu_solid_device_grid_active)
          gpu_solid_p2g_indices_ready = true;
        if (stats.seeded_legacy_topology) {
          std::vector<GPU_STAGE3A::AssemblyGridNode>().swap(
              gpu_solid_legacy_q2_topology_seed);
        }
        ZIRAN_INFO("GPU solid resident Q2 P2G: particles=", stats.particles,
                   " nodes=", stats.nodes, " host_download_bytes=",
                   stats.host_download_bytes, " topology_bytes=",
                   stats.topology_download_bytes, " velocity_bytes=",
                   stats.velocity_download_bytes, " topology_reused=",
                   stats.reused_static_topology ? 1 : 0,
                   " topology_seeded=",
                   stats.seeded_legacy_topology ? 1 : 0,
                   " topology_canonical=",
                   stats.assigned_canonical_topology ? 1 : 0,
                   " p2g_ms=", stats.p2g_ms,
                   " download_ms=", stats.download_ms,
                   " total_ms=", stats.total_ms,
                   " device_grid=", gpu_solid_device_grid_active ? 1 : 0);
        return;
      }
      if (category == MATERIAL_PHASE_SOLID &&
          !gpu_solid_host_dynamic_state_valid)
        synchronizeSolidCompatibilityForHostOutput();
    }
    if (Base::symplectic) {
      Base::accumulateParticleForces();
      Base::particlesToGrid();
    } else {
      Base::particlesToGrid();
    }
  }

  void setupSolidDeviceCallbacks() {
    // New implicit step: grid topology is rebuilt, so the device must re-upload
    // static state on the first trial-state call of this step.
    gpu_solid_trial_static_ready = false;
    gpu_solid_pcg_static_ready = false;
    gpu_solid_trial_device_tangent_ready = false;
    gpu_solid_trial_grad_velocity_deferred = false;
    gpu_solid_trial_force_energy_valid = false;
    gpu_solid_trial_force_energy = 0;
    gpu_solid_device_newton_vectors_active = false;
    gpu_solid_device_corotated_vectors_active = false;
    gpu_solid_device_newton_step_ready = false;
    gpu_solid_final_grid_device_ready = false;
    Base::device_backward_euler_start = [this]() {
      if constexpr (dim != 3)
        return false;
      if (!gpu_solid_device_grid_active ||
          !canUseResidentSolidDeviceGrid() ||
          !Base::collision_nodes.empty() ||
          gpu_solid_p2g_node_map.size == 0 ||
          gpu_solid_p2g_node_map.size !=
              static_cast<std::size_t>(Base::num_nodes))
        return false;
      // The persistent Q2 map owns mass, v^n, dv and the trial velocity.  The
      // generic Newton driver only needs correctly shaped compatibility
      // matrices; no host mass/preconditioner or SPGrid velocity is consumed.
      Base::dv.resize(dim, static_cast<int>(gpu_solid_p2g_node_map.size));
      Base::vn.resize(dim, static_cast<int>(gpu_solid_p2g_node_map.size));
      Base::dv.setZero();
      Base::vn.setZero();
      ZIRAN_INFO("Solid backward Euler node lifecycle remains device-resident: "
                 "nodes=", gpu_solid_p2g_node_map.size);
      return true;
    };
    Base::device_backward_euler_finish = [this]() {
      return gpu_solid_final_grid_device_ready;
    };
    Base::objective.device_node_state_owned = [this]() {
      return Base::device_backward_euler_active;
    };
    if (gpu_solid_implicit_state) {
      Base::objective.device_state_update = [this]() {
        ZIRAN_NAMED_TIMER("gpuSolidTrialState");
        gpu_solid_trial_force_energy_valid = false;
        if constexpr (dim != 3)
          return false;
        if (Base::config_scheme != CONFIG_TOTAL_LAGRANGIAN ||
            !Base::force || !Base::force->material_force)
          return false;
        const bool has_pd = particles.exist(
            MaterialForce::template f_constitutive_model_name<PDIsotropic<T, dim>>());
        const bool has_corotated = particles.exist(
            MaterialForce::template f_constitutive_model_name<CorotatedIsotropic<T, dim>>());
        if (!has_pd && !has_corotated)
          return false;
        // The device bridge currently mirrors the unilateral parallel/GHOST
        // helper. A bilateral parallel spring has a different damping law and
        // deliberately falls back rather than changing its semantics.
        if (Base::force->multi_target_pinning &&
            !Base::force->multi_target_pinning->collider_spring)
          return false;

        if (has_corotated) {
          // Corotated's CPU matrix-free fallback reads a mutable SVD scratch.
          // Until that scratch itself is device-resident, never pair the GPU
          // trial state with the CPU linear solver: that would mix a current
          // GPU residual with a stale CPU Hessian.  The full A/B path enables
          // both callbacks and consumes the GPU-projected Hessian below.
          if (!gpu_solid_implicit_pcg)
            return false;
          auto* F = particles.DataManager::getPointer(MaterialForce::F_name());
          auto* J = particles.DataManager::getPointer(MaterialForce::J_name());
          const auto* X0 = particles.DataManager::getPointer(X0_name<TV>());
          const auto* volume = particles.DataManager::getPointer(element_measure_name<T>());
          const auto* model = particles.DataManager::getPointer(
              MaterialForce::template f_constitutive_model_name<CorotatedIsotropic<T, dim>>());
          if (!F || !J || !X0 || !volume || !model)
            return false;
          // The CUDA path implements the production/default projected
          // CorotatedIsotropic Hessian (`project == true`). Preserve exact CPU
          // semantics for the uncommon unprojected variant by falling back.
          for (int p = 0; p < particles.count; ++p)
            if (!(*model)[p].project)
              return false;
          const bool state_oracle =
              std::getenv("ZIRAN_SOLID_GPU_STATE_ORACLE") != nullptr;
          const bool resident_device_grid = gpu_solid_device_grid_active &&
              !state_oracle && Base::collision_nodes.empty() &&
              gpu_solid_p2g_node_map.size ==
                  static_cast<std::size_t>(Base::num_nodes);
          std::vector<double> cpu_velocity, cpu_grad_velocity, cpu_F, cpu_position,
              cpu_force_stress, cpu_force;
          if (state_oracle) {
            ZIRAN_INFO("GPU solid Corotated trial-state CPU oracle enabled");
            Base::force->updateStrainAndPositions();
            const std::size_t count = static_cast<std::size_t>(particles.count);
            cpu_velocity.resize(3 * count);
            cpu_grad_velocity.resize(9 * count);
            cpu_F.resize(9 * count);
            cpu_position.resize(3 * count);
            cpu_force_stress.resize(9 * count);
            cpu_force.resize(3 * count);
            for (int p = 0; p < particles.count; ++p)
              for (int row = 0; row < 3; ++row) {
                cpu_velocity[3 * p + row] = Base::scratch_vp(row, p);
                cpu_position[3 * p + row] = Base::scratch_xp[p](row);
                cpu_force[3 * p + row] = Base::scratch_fp(row, p);
                for (int col = 0; col < 3; ++col) {
                  cpu_grad_velocity[9 * p + 3 * row + col] =
                      Base::scratch_gradV[p](row, col);
                  cpu_F[9 * p + 3 * row + col] = (*F)[p](row, col);
                  cpu_force_stress[9 * p + 3 * row + col] =
                      Base::scratch_force_stress[p](row, col);
                }
              }
          }
          if (!Base::device_backward_euler_active)
            Base::force->restoreStrain();
          GPU_SOLID_IMPLICIT::CorotatedTrialStateInput input;
          input.dx = static_cast<double>(Base::dx);
          input.dt = static_cast<double>(Base::dt);
          input.enable_tl_contact = Base::force->lagrangian_contact != nullptr;
          // Pinning helpers may update their target/scratch state between
          // Newton evaluations. Reuse the whole Corotated trial payload only
          // for the material-only case; pinned scenes still reuse resident
          // particle/material storage but refresh topology and compact
          // pinning metadata on every Newton state.
          input.reuse_static = gpu_solid_trial_static_ready &&
              (resident_device_grid ||
               (!Base::force->pinning && !Base::force->multi_target_pinning));
          input.resident_particles =
              GPU_STAGE3A::getPersistentSolidParticleStateDeviceView(
                  gpu_solid_particle_state);
          if (resident_device_grid && !input.reuse_static) {
            input.resident_nodes = gpu_solid_p2g_node_map;
            input.initial_velocity_increment = {
                static_cast<double>(Base::gravity[0] * Base::dt),
                static_cast<double>(Base::gravity[1] * Base::dt),
                static_cast<double>(Base::gravity[2] * Base::dt)};
          }
          input.scatter_residual = gpu_solid_implicit_pcg && !state_oracle &&
              Base::force->lagrangian_contact == nullptr &&
              gpu_solid_device_resident && input.resident_particles.size != 0;
          const bool device_newton_vectors = input.scatter_residual &&
              resident_device_grid &&
              std::getenv("ZIRAN_SOLID_GPU_PCG_ORACLE") == nullptr;
          input.download_node_residual = !device_newton_vectors;
          if (!resident_device_grid) {
            input.nodes.reserve(static_cast<std::size_t>(Base::num_nodes));
            Base::grid.iterateGridSerial([&](IV node, GridState<T, dim>& g) {
              GPU_SOLID_IMPLICIT::PdTrialNode entry;
              entry.node.key =
                  GPU_STAGE3A::packGridKey3D(node[0], node[1], node[2]);
              entry.node.idx = static_cast<int>(g.idx);
              entry.node.mass = static_cast<double>(g.m);
              entry.velocity = {
                  static_cast<double>(Base::vn(0, g.idx) + Base::dv(0, g.idx)),
                  static_cast<double>(Base::vn(1, g.idx) + Base::dv(1, g.idx)),
                  static_cast<double>(Base::vn(2, g.idx) + Base::dv(2, g.idx))};
              input.nodes.push_back(entry);
            });
          }
          input.particles.resize(static_cast<std::size_t>(particles.count));
          for (int p = 0; p < particles.count; ++p) {
            const TV& x = particles.X.array[p];
            auto& dst = input.particles[static_cast<std::size_t>(p)];
            dst.x = {static_cast<double>(x[0]), static_cast<double>(x[1]),
                     static_cast<double>(x[2])};
            dst.x0 = {static_cast<double>((*X0)[p][0]), static_cast<double>((*X0)[p][1]),
                      static_cast<double>((*X0)[p][2])};
            dst.volume = static_cast<double>((*volume)[p]);
            dst.mass = static_cast<double>(particles.mass[p]);
            dst.mu = static_cast<double>((*model)[p].mu);
            dst.lambda = static_cast<double>((*model)[p].lambda);
            for (int row = 0; row < 3; ++row)
              for (int col = 0; col < 3; ++col)
                dst.F[3 * row + col] = static_cast<double>((*F)[p](row, col));
          }
          if (Base::force->pinning) {
            auto& helper = *Base::force->pinning;
            const bool device_pinning =
                gpu_solid_device_ordinary_pinning_active &&
                input.resident_particles.size != 0;
            for (auto iter = particles.subsetIter(
                     helper.target.ranges,
                     MpmPinningForce<T, dim>::target_name(),
                     MpmPinningForce<T, dim>::target_scratch_name()); iter;
                 ++iter) {
              const int p = iter.entryId();
              const auto& target = iter.template get<0>();
              auto& scratch = iter.template get<1>();
              scratch.A = target.k + target.d / Base::dt;
              auto& dst = input.particles[static_cast<std::size_t>(p)];
              if (device_pinning) {
                dst.pinning_k = static_cast<double>(target.k);
                dst.pinning_d = static_cast<double>(target.d);
                dst.pinning_target_x = {static_cast<double>(target.x[0]),
                                        static_cast<double>(target.x[1]),
                                        static_cast<double>(target.x[2])};
                dst.pinning_target_v = {static_cast<double>(target.v[0]),
                                        static_cast<double>(target.v[1]),
                                        static_cast<double>(target.v[2])};
                dst.pinning_from_resident_x0 = 1;
              } else {
                const TV& xn = (*X0)[p];
                const TV xt = target.x + target.v * Base::dt;
                scratch.b = target.k * xt -
                    (target.d / Base::dt) * (-xn - xt + target.x);
                dst.pinning_a = static_cast<double>(scratch.A);
                dst.pinning_b = {static_cast<double>(scratch.b[0]),
                                 static_cast<double>(scratch.b[1]),
                                 static_cast<double>(scratch.b[2])};
              }
            }
          }
          if (gpu_solid_device_ghost_contact_active) {
            auto to_ghost_vec = [](const GPU_STAGE2::Vec3d& value) {
              return GPU_STAGE3A::Vec3d{value.x, value.y, value.z};
            };
            input.ghost_collision.outer_min =
                to_ghost_vec(gpu_box_shell_collision.outer_min);
            input.ghost_collision.outer_max =
                to_ghost_vec(gpu_box_shell_collision.outer_max);
            input.ghost_collision.inner_min =
                to_ghost_vec(gpu_box_shell_collision.inner_min);
            input.ghost_collision.inner_max =
                to_ghost_vec(gpu_box_shell_collision.inner_max);
            input.ghost_collision.hole_min =
                to_ghost_vec(gpu_box_shell_collision.hole_min);
            input.ghost_collision.hole_max =
                to_ghost_vec(gpu_box_shell_collision.hole_max);
            input.ghost_collision.has_hole = gpu_box_shell_collision.has_hole;
            input.ghost_collision.valid = gpu_box_shell_collision.valid;
            input.ghost_penalty =
                static_cast<double>(implicit_penalty_collision);
          } else if (Base::force->multi_target_pinning) {
            auto& helper = *Base::force->multi_target_pinning;
            for (auto iter = particles.subsetIter(
                     helper.target.ranges,
                     MpmMultiTargetPinningForce<T, dim>::target_name()); iter;
                 ++iter) {
              const int p = iter.entryId();
              const auto& target = iter.template get<0>();
              auto& dst = input.particles[static_cast<std::size_t>(p)];
              dst.parallel_target_begin = static_cast<int>(input.parallel_targets.size());
              for (const TV& target_x : target.x)
                input.parallel_targets.push_back({
                    {static_cast<double>(target_x[0]), static_cast<double>(target_x[1]),
                     static_cast<double>(target_x[2])}, static_cast<double>(target.k)});
              dst.parallel_target_count = static_cast<int>(input.parallel_targets.size()) -
                  dst.parallel_target_begin;
            }
          }
          GPU_SOLID_IMPLICIT::PdTrialStateOutput output;
          GPU_SOLID_IMPLICIT::PdTrialStateStats stats;
          GPU_SOLID_IMPLICIT::evaluateCorotatedTrialState3D(
              gpu_solid_pd_operator, input, output,
              gpu_solid_trial_corotated_hessian, &stats);
          gpu_solid_trial_force_energy = output.force_energy;
          gpu_solid_trial_force_energy_valid =
              Base::force->lagrangian_contact == nullptr;
          gpu_solid_trial_static_ready = true;
          if (state_oracle) {
            auto report_oracle = [](const char* name, const std::vector<double>& cpu,
                                    const std::vector<double>& gpu) {
              double max_abs = 0, cpu_l2 = 0, diff_l2 = 0;
              for (std::size_t i = 0; i < cpu.size(); ++i) {
                const double diff = gpu[i] - cpu[i];
                max_abs = std::max(max_abs, std::abs(diff));
                cpu_l2 += cpu[i] * cpu[i];
                diff_l2 += diff * diff;
              }
              ZIRAN_INFO("GPU solid Corotated trial oracle ", name,
                         ": max_abs=", max_abs, " rel_l2=",
                         std::sqrt(diff_l2 / std::max(cpu_l2, 1e-300)));
            };
            report_oracle("velocity", cpu_velocity, output.particle_velocity);
            report_oracle("gradV", cpu_grad_velocity, output.particle_grad_velocity);
            report_oracle("F", cpu_F, output.deformation_gradient);
            report_oracle("xp", cpu_position, output.trial_position);
            report_oracle("force_stress", cpu_force_stress, output.force_stress);
            report_oracle("fp", cpu_force, output.force);
          }
          gpu_solid_trial_device_tangent_ready = input.scatter_residual;
          gpu_solid_trial_grad_velocity_deferred = input.scatter_residual;
          gpu_solid_device_newton_vectors_active = device_newton_vectors;
          gpu_solid_device_corotated_vectors_active =
              device_newton_vectors;
          if (input.scatter_residual) {
            gpu_solid_trial_tangent_a.clear();
            gpu_solid_trial_tangent_matrix.clear();
          } else {
            gpu_solid_trial_tangent_a = output.tangent_a;
            gpu_solid_trial_tangent_matrix = output.tangent_matrix;
            for (int p = 0; p < particles.count; ++p) {
              Base::scratch_vp(0, p) = static_cast<T>(output.particle_velocity[3 * p + 0]);
              Base::scratch_vp(1, p) = static_cast<T>(output.particle_velocity[3 * p + 1]);
              Base::scratch_vp(2, p) = static_cast<T>(output.particle_velocity[3 * p + 2]);
              Base::scratch_xp[p] = TV(static_cast<T>(output.trial_position[3 * p + 0]),
                                       static_cast<T>(output.trial_position[3 * p + 1]),
                                       static_cast<T>(output.trial_position[3 * p + 2]));
              Base::scratch_fp(0, p) = static_cast<T>(output.force[3 * p + 0]);
              Base::scratch_fp(1, p) = static_cast<T>(output.force[3 * p + 1]);
              Base::scratch_fp(2, p) = static_cast<T>(output.force[3 * p + 2]);
              (*J)[p] = static_cast<T>(output.determinant[static_cast<std::size_t>(p)]);
              for (int row = 0; row < 3; ++row)
                for (int col = 0; col < 3; ++col) {
                  (*F)[p](row, col) = static_cast<T>(
                      output.deformation_gradient[static_cast<std::size_t>(9 * p + 3 * row + col)]);
                  Base::scratch_gradV[p](row, col) = static_cast<T>(
                      output.particle_grad_velocity[static_cast<std::size_t>(9 * p + 3 * row + col)]);
                  Base::scratch_force_stress[p](row, col) = static_cast<T>(
                      output.force_stress[static_cast<std::size_t>(9 * p + 3 * row + col)]);
                }
            }
          }
          if (std::getenv("ZIRAN_SOLID_GPU_STATE_LOG") != nullptr)
            ZIRAN_INFO("GPU solid Corotated trial state: particles=", particles.count,
                       " tl_contact_particles=", stats.active_tl_contacts,
                       " upload_ms=", stats.upload_ms, " gather_ms=", stats.gather_ms,
                       " contact_ms=", stats.contact_ms, " download_ms=", stats.download_ms);
          return true;
        }

        auto* F = particles.DataManager::getPointer(MaterialForce::F_name());
        auto* J = particles.DataManager::getPointer(MaterialForce::J_name());
        const auto* X0 = particles.DataManager::getPointer(X0_name<TV>());
        const auto* volume = particles.DataManager::getPointer(element_measure_name<T>());
        const auto* model = particles.DataManager::getPointer(
            MaterialForce::template f_constitutive_model_name<PDIsotropic<T, dim>>());
        if (!F || !J || !X0 || !volume || !model)
          return false;
        // Optional one-state oracle: run the unmodified CPU traversal first,
        // save its material residual scratch, then restore strain and evaluate
        // the exact same Newton trial on CUDA. It is deliberately opt-in
        // because TL contact's CPU SpatialHash is expensive.
        const bool state_oracle =
            std::getenv("ZIRAN_SOLID_GPU_STATE_ORACLE") != nullptr;
        const bool resident_device_grid = gpu_solid_device_grid_active &&
            !state_oracle && Base::collision_nodes.empty() &&
            gpu_solid_p2g_node_map.size ==
                static_cast<std::size_t>(Base::num_nodes);
        if (state_oracle)
          ZIRAN_INFO("GPU solid trial-state CPU oracle enabled");
        std::vector<double> cpu_velocity, cpu_grad_velocity, cpu_F, cpu_position,
            cpu_force_stress, cpu_force;
        if (state_oracle) {
          Base::force->updateStrainAndPositions();
          const std::size_t count = static_cast<std::size_t>(particles.count);
          cpu_velocity.resize(3 * count);
          cpu_grad_velocity.resize(9 * count);
          cpu_F.resize(9 * count);
          cpu_position.resize(3 * count);
          cpu_force_stress.resize(9 * count);
          cpu_force.resize(3 * count);
          for (int p = 0; p < particles.count; ++p) {
            for (int row = 0; row < 3; ++row) {
              cpu_velocity[3 * p + row] = Base::scratch_vp(row, p);
              cpu_position[3 * p + row] = Base::scratch_xp[p](row);
              cpu_force[3 * p + row] = Base::scratch_fp(row, p);
              for (int col = 0; col < 3; ++col) {
                cpu_grad_velocity[9 * p + 3 * row + col] =
                    Base::scratch_gradV[p](row, col);
                cpu_F[9 * p + 3 * row + col] = (*F)[p](row, col);
                cpu_force_stress[9 * p + 3 * row + col] =
                    Base::scratch_force_stress[p](row, col);
              }
            }
          }
        }
        // Recreate the CPU Newton contract: F/J begin from backupStrain() at
        // every trial velocity. The CUDA kernel then evaluates F + dt grad(v)
        // and fills all residual scratch fields.
        if (!Base::device_backward_euler_active)
          Base::force->restoreStrain();

        GPU_SOLID_IMPLICIT::PdTrialStateInput input;
        input.dx = static_cast<double>(Base::dx);
        input.dt = static_cast<double>(Base::dt);
        input.enable_tl_contact = Base::force->lagrangian_contact != nullptr;
        input.reuse_static = gpu_solid_trial_static_ready;
        input.resident_particles =
            GPU_STAGE3A::getPersistentSolidParticleStateDeviceView(
                gpu_solid_particle_state);
        if (resident_device_grid && !input.reuse_static) {
          input.resident_nodes = gpu_solid_p2g_node_map;
          input.initial_velocity_increment = {
              static_cast<double>(Base::gravity[0] * Base::dt),
              static_cast<double>(Base::gravity[1] * Base::dt),
              static_cast<double>(Base::gravity[2] * Base::dt)};
        }
        // Scatter the material force to node residual on the device so the
        // Newton residual skips the CPU raster and the full per-particle
        // download. Only meaningful when the device PCG owns the linear solve.
        // The oracle intentionally compares every per-particle state field, so
        // retain the full download in that diagnostic mode. Production keeps
        // tangent and per-iteration gradV on device; only node residual returns
        // during Newton and the final gradV returns once after convergence.
        const bool resident_linesearch_trial = Base::newton.linesearch &&
            gpu_solid_device_resident && input.resident_particles.size != 0;
        input.scatter_residual = gpu_solid_implicit_pcg && !state_oracle &&
            (!Base::newton.linesearch || resident_linesearch_trial);
        // Line search still owns dv and its trial sequence on the host, but it
        // only needs the compact node residual plus a scalar device energy.
        // The no-line-search path can additionally keep Newton vectors on the
        // device across iterations.
        const bool device_newton_vectors = input.scatter_residual &&
            (!Base::newton.linesearch || resident_device_grid) &&
            std::getenv("ZIRAN_SOLID_GPU_PCG_ORACLE") == nullptr;
        input.download_node_residual = !device_newton_vectors;
        std::vector<TM> trial_node_projection(
            static_cast<std::size_t>(Base::num_nodes), TM::Identity());
        for (const auto& collision : Base::collision_nodes)
          trial_node_projection[static_cast<std::size_t>(collision.node_id)] =
              collision.P;
        if (!resident_device_grid) {
          input.nodes.reserve(static_cast<std::size_t>(Base::num_nodes));
          Base::grid.iterateGridSerial([&](IV node, GridState<T, dim>& g) {
            GPU_SOLID_IMPLICIT::PdTrialNode entry;
            entry.node.key =
                GPU_STAGE3A::packGridKey3D(node[0], node[1], node[2]);
            entry.node.idx = static_cast<int>(g.idx);
            entry.node.mass = static_cast<double>(g.m);
            const TM& projection =
                trial_node_projection[static_cast<std::size_t>(g.idx)];
            for (int row = 0; row < 3; ++row)
              for (int col = 0; col < 3; ++col)
                entry.node.projection[3 * row + col] =
                    static_cast<double>(projection(row, col));
            entry.base_velocity = {
                static_cast<double>(Base::vn(0, g.idx)),
                static_cast<double>(Base::vn(1, g.idx)),
                static_cast<double>(Base::vn(2, g.idx))};
            entry.velocity_increment = {
                static_cast<double>(Base::dv(0, g.idx)),
                static_cast<double>(Base::dv(1, g.idx)),
                static_cast<double>(Base::dv(2, g.idx))};
            entry.velocity = {
                static_cast<double>(Base::vn(0, g.idx) + Base::dv(0, g.idx)),
                static_cast<double>(Base::vn(1, g.idx) + Base::dv(1, g.idx)),
                static_cast<double>(Base::vn(2, g.idx) + Base::dv(2, g.idx))};
            input.nodes.push_back(entry);
          });
        }
        if (!input.reuse_static) {
          input.particles.resize(static_cast<std::size_t>(particles.count));
          tbb::parallel_for(0, particles.count, [&](int p) {
            const TV& x = particles.X.array[p];
            auto& dst = input.particles[static_cast<std::size_t>(p)];
            dst.x = {static_cast<double>(x[0]), static_cast<double>(x[1]),
                     static_cast<double>(x[2])};
            dst.x0 = {static_cast<double>((*X0)[p][0]), static_cast<double>((*X0)[p][1]),
                      static_cast<double>((*X0)[p][2])};
            dst.volume = static_cast<double>((*volume)[p]);
            dst.mass = static_cast<double>(particles.mass[p]);
            dst.mu = static_cast<double>((*model)[p].mu);
            for (int row = 0; row < 3; ++row)
              for (int col = 0; col < 3; ++col)
                dst.F[3 * row + col] = static_cast<double>((*F)[p](row, col));
          });
        }

        // Populate and retain the ordinary pinning scratch A/b exactly as the
        // CPU helper does; it is still used by totalEnergy and by the device
        // PCG fallback assembly.
        if (!input.reuse_static && Base::force->pinning) {
          auto& helper = *Base::force->pinning;
          const bool device_pinning =
              gpu_solid_device_ordinary_pinning_active &&
              input.resident_particles.size != 0;
          for (auto iter = particles.subsetIter(
                   helper.target.ranges,
                   MpmPinningForce<T, dim>::target_name(),
                   MpmPinningForce<T, dim>::target_scratch_name()); iter;
               ++iter) {
            const int p = iter.entryId();
            const auto& target = iter.template get<0>();
            auto& scratch = iter.template get<1>();
            scratch.A = target.k + target.d / Base::dt;
            auto& dst = input.particles[static_cast<std::size_t>(p)];
            if (device_pinning) {
              dst.pinning_k = static_cast<double>(target.k);
              dst.pinning_d = static_cast<double>(target.d);
              dst.pinning_target_x = {static_cast<double>(target.x[0]),
                                      static_cast<double>(target.x[1]),
                                      static_cast<double>(target.x[2])};
              dst.pinning_target_v = {static_cast<double>(target.v[0]),
                                      static_cast<double>(target.v[1]),
                                      static_cast<double>(target.v[2])};
              dst.pinning_from_resident_x0 = 1;
            } else {
              const TV& xn = (*X0)[p];
              const TV xt = target.x + target.v * Base::dt;
              scratch.b = target.k * xt -
                  (target.d / Base::dt) * (-xn - xt + target.x);
              dst.pinning_a = static_cast<double>(scratch.A);
              dst.pinning_b = {static_cast<double>(scratch.b[0]),
                               static_cast<double>(scratch.b[1]),
                               static_cast<double>(scratch.b[2])};
            }
          }
        }
        if (!input.reuse_static && Base::force->multi_target_pinning) {
          auto& helper = *Base::force->multi_target_pinning;
          for (auto iter = particles.subsetIter(
                   helper.target.ranges,
                   MpmMultiTargetPinningForce<T, dim>::target_name()); iter;
               ++iter) {
            const int p = iter.entryId();
            const auto& target = iter.template get<0>();
            auto& dst = input.particles[static_cast<std::size_t>(p)];
            dst.parallel_target_begin =
                static_cast<int>(input.parallel_targets.size());
            for (const TV& target_x : target.x) {
              input.parallel_targets.push_back({
                  {static_cast<double>(target_x[0]), static_cast<double>(target_x[1]),
                   static_cast<double>(target_x[2])}, static_cast<double>(target.k)});
            }
            dst.parallel_target_count = static_cast<int>(input.parallel_targets.size()) -
                dst.parallel_target_begin;
          }
        }

        GPU_SOLID_IMPLICIT::PdTrialStateOutput& output = gpu_solid_trial_output;
        GPU_SOLID_IMPLICIT::PdTrialStateStats stats;
        gpu_solid_trial_corotated_hessian.clear();
        GPU_SOLID_IMPLICIT::evaluatePdTrialState3D(
            gpu_solid_pd_operator, input, output, &stats);
        gpu_solid_trial_force_energy = output.force_energy;
        gpu_solid_trial_force_energy_valid =
            Base::force->lagrangian_contact == nullptr;
        // Static topology/particles now reside on the device; subsequent Newton
        // iterations of this step upload only the trial grid velocity.
        gpu_solid_trial_static_ready = true;
        if (state_oracle) {
          auto report_oracle = [](const char* name, const std::vector<double>& cpu,
                                  const std::vector<double>& gpu) {
            double max_abs = 0, cpu_l2 = 0, diff_l2 = 0;
            for (std::size_t i = 0; i < cpu.size(); ++i) {
              const double diff = gpu[i] - cpu[i];
              max_abs = std::max(max_abs, std::abs(diff));
              cpu_l2 += cpu[i] * cpu[i];
              diff_l2 += diff * diff;
            }
            ZIRAN_INFO("GPU solid trial oracle ", name, ": max_abs=", max_abs,
                       " rel_l2=", std::sqrt(diff_l2 / std::max(cpu_l2, 1e-300)));
          };
          report_oracle("velocity", cpu_velocity, output.particle_velocity);
          report_oracle("gradV", cpu_grad_velocity, output.particle_grad_velocity);
          report_oracle("F", cpu_F, output.deformation_gradient);
          report_oracle("xp", cpu_position, output.trial_position);
          report_oracle("force_stress", cpu_force_stress, output.force_stress);
          report_oracle("fp", cpu_force, output.force);
        }
        gpu_solid_trial_device_tangent_ready = input.scatter_residual;
        gpu_solid_trial_grad_velocity_deferred = input.scatter_residual;
        gpu_solid_device_newton_vectors_active = device_newton_vectors;
        gpu_solid_device_corotated_vectors_active = false;
        if (input.scatter_residual) {
          gpu_solid_trial_tangent_a.clear();
          gpu_solid_trial_tangent_matrix.clear();
        } else {
          gpu_solid_trial_tangent_a = output.tangent_a;
          gpu_solid_trial_tangent_matrix = output.tangent_matrix;
        }
        tbb::parallel_for(0, particles.count, [&](int p) {
          if (!input.scatter_residual) {
            Base::scratch_vp(0, p) = static_cast<T>(output.particle_velocity[3 * p + 0]);
            Base::scratch_vp(1, p) = static_cast<T>(output.particle_velocity[3 * p + 1]);
            Base::scratch_vp(2, p) = static_cast<T>(output.particle_velocity[3 * p + 2]);
            Base::scratch_xp[p] = TV(static_cast<T>(output.trial_position[3 * p + 0]),
                                     static_cast<T>(output.trial_position[3 * p + 1]),
                                     static_cast<T>(output.trial_position[3 * p + 2]));
            Base::scratch_fp(0, p) = static_cast<T>(output.force[3 * p + 0]);
            Base::scratch_fp(1, p) = static_cast<T>(output.force[3 * p + 1]);
            Base::scratch_fp(2, p) = static_cast<T>(output.force[3 * p + 2]);
            (*J)[p] = static_cast<T>(output.determinant[static_cast<std::size_t>(p)]);
          }
          for (int row = 0; row < 3; ++row)
            for (int col = 0; col < 3; ++col) {
              if (!input.scatter_residual)
                (*F)[p](row, col) = static_cast<T>(
                    output.deformation_gradient[static_cast<std::size_t>(9 * p + 3 * row + col)]);
              if (!input.scatter_residual)
                Base::scratch_gradV[p](row, col) = static_cast<T>(
                    output.particle_grad_velocity[static_cast<std::size_t>(9 * p + 3 * row + col)]);
              if (!input.scatter_residual)
                Base::scratch_force_stress[p](row, col) = static_cast<T>(
                    output.force_stress[static_cast<std::size_t>(9 * p + 3 * row + col)]);
            }
        });
        if (std::getenv("ZIRAN_SOLID_GPU_STATE_LOG") != nullptr)
          ZIRAN_INFO("GPU solid PD trial state: particles=", particles.count,
                     " tl_contact_particles=", stats.active_tl_contacts,
                     " upload_ms=", stats.upload_ms,
                     " gather_ms=", stats.gather_ms,
                     " contact_ms=", stats.contact_ms,
                     " download_ms=", stats.download_ms);
        return true;
      };
    } else {
      Base::objective.device_state_update = {};
      gpu_solid_trial_tangent_a.clear();
      gpu_solid_trial_tangent_matrix.clear();
      gpu_solid_trial_corotated_hessian.clear();
    }
    if (gpu_solid_implicit_state) {
      Base::objective.device_force_energy = [this](T& energy) {
        if (!gpu_solid_trial_force_energy_valid)
          return false;
        energy = static_cast<T>(gpu_solid_trial_force_energy);
        return true;
      };
    } else {
      Base::objective.device_force_energy = {};
    }
    if (gpu_solid_implicit_state && gpu_solid_implicit_pcg) {
      Base::objective.device_total_energy = [this](T& energy) {
        if (!gpu_solid_device_grid_active ||
            !gpu_solid_device_newton_vectors_active ||
            !gpu_solid_trial_force_energy_valid)
          return false;
        const TV& gravity = Base::gravity;
        energy = static_cast<T>(
            GPU_SOLID_IMPLICIT::computePdNewtonTotalEnergy3D(
                gpu_solid_pd_operator,
                {static_cast<double>(gravity[0]),
                 static_cast<double>(gravity[1]),
                 static_cast<double>(gravity[2])},
                static_cast<double>(Base::dt)));
        return true;
      };
    } else {
      Base::objective.device_total_energy = {};
    }
    if (gpu_solid_implicit_pcg) {
      Base::objective.device_linear_solve = [this](typename Base::TVStack& ddv,
                                                   const typename Base::TVStack& rhs,
                                                   T relative_tolerance) {
        if constexpr (dim != 3)
          return false;
        const bool has_pd = particles.exist(
            MaterialForce::template f_constitutive_model_name<PDIsotropic<T, dim>>());
        const bool has_linear_corotated = particles.exist(
            MaterialForce::template f_constitutive_model_name<LinearCorotated<T, dim>>());
        const bool has_corotated = particles.exist(
            MaterialForce::template f_constitutive_model_name<CorotatedIsotropic<T, dim>>());
        if (!has_pd && !has_linear_corotated && !has_corotated)
          return false;
        GPU_SOLID_IMPLICIT::PdOperatorInput input;
        input.dx = static_cast<double>(Base::dx);
        input.dt = static_cast<double>(Base::dt);
        const bool resident_device_operator = (has_pd || has_corotated) &&
            gpu_solid_device_grid_active &&
            gpu_solid_device_newton_vectors_active &&
            Base::collision_nodes.empty();
        std::vector<TM> node_projection(static_cast<std::size_t>(Base::num_nodes),
            TM::Identity());
        for (const auto& collision : Base::collision_nodes)
          node_projection[static_cast<std::size_t>(collision.node_id)] = collision.P;
        if (!resident_device_operator) {
          input.nodes.reserve(static_cast<std::size_t>(Base::num_nodes));
          Base::grid.iterateGridSerial([&](IV node, GridState<T, dim>& g) {
            GPU_SOLID_IMPLICIT::SolidNode entry;
            entry.key =
                GPU_STAGE3A::packGridKey3D(node[0], node[1], node[2]);
            entry.idx = static_cast<int>(g.idx);
            entry.mass = static_cast<double>(g.m);
            const TM& projection =
                node_projection[static_cast<std::size_t>(g.idx)];
            for (int row = 0; row < 3; ++row)
              for (int col = 0; col < 3; ++col)
                entry.projection[3 * row + col] =
                    static_cast<double>(projection(row, col));
            input.nodes.push_back(entry);
          });
        }
        const auto* volume = particles.DataManager::getPointer(element_measure_name<T>());
        const auto* pinning = particles.DataManager::getPointer(
            MpmPinningForce<T, dim>::target_scratch_name());
        std::vector<double> host_rhs;
        if (!gpu_solid_device_newton_vectors_active) {
          host_rhs.resize(static_cast<std::size_t>(3 * Base::num_nodes));
          for (int n = 0; n < Base::num_nodes; ++n)
            for (int d = 0; d < dim; ++d)
              host_rhs[static_cast<std::size_t>(3 * n + d)] = rhs(d, n);
        }
        std::vector<double> host_ddv;
        GPU_SOLID_IMPLICIT::PdPcgStats pcg_stats;
        if (has_pd) {
          const auto* model = particles.DataManager::getPointer(
              MaterialForce::template f_constitutive_model_name<PDIsotropic<T, dim>>());
          // The trial-state tangent already resides on the device
          // (state.trial_tangent_matrix); inject it there instead of a
          // device->host->device round trip. Static particle fields and grid
          // topology are uploaded only on the first PCG solve of this step.
          const bool device_tangent = gpu_solid_trial_device_tangent_ready;
          input.reuse_static = gpu_solid_pcg_static_ready;
          input.reuse_topology = resident_device_operator && !input.reuse_static;
          input.use_device_trial_particles =
              resident_device_operator && !input.reuse_static;
          input.use_device_tangent = device_tangent;
          if (!input.reuse_static && !input.use_device_trial_particles) {
            input.particles.resize(static_cast<std::size_t>(particles.count));
            for (int p = 0; p < particles.count; ++p) {
              const TV& x = particles.X.array[p];
              input.particles[static_cast<std::size_t>(p)] = {{static_cast<double>(x[0]),
                  static_cast<double>(x[1]), static_cast<double>(x[2])},
                  static_cast<double>((*volume)[p]), static_cast<double>((*model)[p].mu), 0};
            }
            if (!device_tangent && pinning) {
              for (auto iter = particles.subsetIter(pinning->ranges,
                       MpmPinningForce<T, dim>::target_scratch_name()); iter;
                   ++iter)
                input.particles[static_cast<std::size_t>(iter.entryId())].pinning_a =
                    static_cast<double>(iter.template get<0>().A);
            }
          }
          if (gpu_solid_device_newton_vectors_active) {
            GPU_SOLID_IMPLICIT::solvePdPcgDeviceResidual3D(
                gpu_solid_pd_operator, input,
                static_cast<double>(relative_tolerance),
                static_cast<double>(Base::objective.linear_solver->tolerance),
                Base::objective.linear_solver->max_iterations, &pcg_stats);
            gpu_solid_pcg_static_ready = true;
            gpu_solid_device_newton_step_ready = true;
            ZIRAN_INFO("GPU solid implicit PCG: energy=PDIsotropic",
                       " iterations=", pcg_stats.iterations,
                       " initial=", pcg_stats.initial_preconditioned_norm,
                       " final=", pcg_stats.final_preconditioned_norm,
                       " upload_ms=", pcg_stats.upload_ms,
                       " solve_ms=", pcg_stats.solve_ms,
                       " download_ms=", pcg_stats.download_ms,
                       " vectors=device");
            return true;
          }
          GPU_SOLID_IMPLICIT::solvePdPcg3D(gpu_solid_pd_operator, input, host_rhs,
              static_cast<double>(relative_tolerance),
              static_cast<double>(Base::objective.linear_solver->tolerance),
              Base::objective.linear_solver->max_iterations, host_ddv, &pcg_stats);
          gpu_solid_pcg_static_ready = true;
          if (std::getenv("ZIRAN_SOLID_GPU_PCG_ORACLE") != nullptr) {
            typename Base::TVStack probe_x(dim, Base::num_nodes);
            for (int n = 0; n < Base::num_nodes; ++n)
              for (int d = 0; d < dim; ++d)
                probe_x(d, n) = static_cast<T>(
                    (((n * 13 + d * 7 + 5) % 19) - 9) * 0.03125);
            Base::objective.project(probe_x);
            typename Base::TVStack cpu_y(dim, Base::num_nodes);
            Base::objective.multiply(probe_x, cpu_y);
            Base::objective.project(cpu_y);
            std::vector<double> host_x(static_cast<std::size_t>(3 * Base::num_nodes));
            for (int n = 0; n < Base::num_nodes; ++n)
              for (int d = 0; d < dim; ++d)
                host_x[static_cast<std::size_t>(3 * n + d)] = probe_x(d, n);
            std::vector<double> gpu_y;
            GPU_SOLID_IMPLICIT::PdOperatorStats operator_stats;
            GPU_SOLID_IMPLICIT::applyPdMatrixFree3D(
                gpu_solid_pd_operator, input, host_x, gpu_y, &operator_stats);
            for (int n = 0; n < Base::num_nodes; ++n) {
              const double y0 = gpu_y[static_cast<std::size_t>(3 * n + 0)];
              const double y1 = gpu_y[static_cast<std::size_t>(3 * n + 1)];
              const double y2 = gpu_y[static_cast<std::size_t>(3 * n + 2)];
              for (int row = 0; row < 3; ++row)
                gpu_y[static_cast<std::size_t>(3 * n + row)] =
                    node_projection[static_cast<std::size_t>(n)](row, 0) * y0 +
                    node_projection[static_cast<std::size_t>(n)](row, 1) * y1 +
                    node_projection[static_cast<std::size_t>(n)](row, 2) * y2;
            }
            double max_abs = 0, cpu_l2 = 0, diff_l2 = 0;
            for (int n = 0; n < Base::num_nodes; ++n)
              for (int d = 0; d < dim; ++d) {
                const double cpu = static_cast<double>(cpu_y(d, n));
                const double diff = gpu_y[static_cast<std::size_t>(3 * n + d)] - cpu;
                max_abs = std::max(max_abs, std::abs(diff));
                cpu_l2 += cpu * cpu;
                diff_l2 += diff * diff;
              }
            ZIRAN_INFO("GPU solid PCG matrix oracle: max_abs=", max_abs,
                       " rel_l2=", std::sqrt(diff_l2 / std::max(cpu_l2, 1e-300)),
                       " apply_ms=", operator_stats.apply_ms);
          }
        } else if (has_linear_corotated) {
          const auto* model = particles.DataManager::getPointer(
              MaterialForce::template f_constitutive_model_name<LinearCorotated<T, dim>>());
          GPU_SOLID_IMPLICIT::LinearCorotatedOperatorInput linear_input;
          linear_input.dx = input.dx;
          linear_input.dt = input.dt;
          linear_input.nodes = input.nodes;
          linear_input.particles.resize(static_cast<std::size_t>(particles.count));
          for (int p = 0; p < particles.count; ++p) {
            const TV& x = particles.X.array[p];
            auto& dst = linear_input.particles[static_cast<std::size_t>(p)];
            dst.x = {static_cast<double>(x[0]), static_cast<double>(x[1]),
                     static_cast<double>(x[2])};
            dst.volume = static_cast<double>((*volume)[p]);
            dst.mu = static_cast<double>((*model)[p].mu);
            dst.lambda = static_cast<double>((*model)[p].lambda);
            for (int row = 0; row < 3; ++row)
              for (int col = 0; col < 3; ++col)
                dst.R[3 * row + col] = static_cast<double>((*model)[p].R(row, col));
          }
          if (pinning) {
            for (auto iter = particles.subsetIter(pinning->ranges,
                     MpmPinningForce<T, dim>::target_scratch_name()); iter;
                 ++iter)
              linear_input.particles[static_cast<std::size_t>(iter.entryId())].pinning_a =
                  static_cast<double>(iter.template get<0>().A);
          }
          GPU_SOLID_IMPLICIT::solveLinearCorotatedPcg3D(
              gpu_solid_pd_operator, linear_input, host_rhs,
              static_cast<double>(relative_tolerance),
              static_cast<double>(Base::objective.linear_solver->tolerance),
              Base::objective.linear_solver->max_iterations, host_ddv, &pcg_stats);
        } else {
          const bool device_trial = gpu_solid_trial_device_tangent_ready;
          if (!device_trial && gpu_solid_trial_corotated_hessian.size() !=
              static_cast<std::size_t>(81 * particles.count))
            return false;
          GPU_SOLID_IMPLICIT::CorotatedOperatorInput corotated_input;
          corotated_input.dx = input.dx;
          corotated_input.dt = input.dt;
          corotated_input.reuse_static =
              device_trial && gpu_solid_pcg_static_ready;
          corotated_input.reuse_topology = resident_device_operator &&
              !corotated_input.reuse_static;
          corotated_input.use_device_trial = device_trial;
          corotated_input.nodes = input.nodes;
          if (!resident_device_operator)
            corotated_input.particles.resize(
                static_cast<std::size_t>(particles.count));
          if (!device_trial) {
            for (int p = 0; p < particles.count; ++p) {
              const TV& x = particles.X.array[p];
              auto& dst = corotated_input.particles[static_cast<std::size_t>(p)];
              dst.x = {static_cast<double>(x[0]), static_cast<double>(x[1]),
                       static_cast<double>(x[2])};
              dst.volume = static_cast<double>((*volume)[p]);
              for (int entry = 0; entry < 81; ++entry)
                dst.projected_hessian[entry] =
                    gpu_solid_trial_corotated_hessian[
                        static_cast<std::size_t>(81 * p + entry)];
            }
          }
          if (!device_trial) {
            if (gpu_solid_trial_tangent_a.size() ==
                static_cast<std::size_t>(particles.count)) {
              const bool has_matrix = gpu_solid_trial_tangent_matrix.size() ==
                  static_cast<std::size_t>(9 * particles.count);
              for (int p = 0; p < particles.count; ++p) {
                auto& dst =
                    corotated_input.particles[static_cast<std::size_t>(p)];
                dst.pinning_a = has_matrix
                    ? 0.0
                    : gpu_solid_trial_tangent_a[static_cast<std::size_t>(p)];
                for (int row = 0; row < 3; ++row)
                  for (int col = 0; col < 3; ++col)
                    dst.pinning_matrix[3 * row + col] = has_matrix
                        ? gpu_solid_trial_tangent_matrix[
                              static_cast<std::size_t>(
                                  9 * p + 3 * row + col)]
                        : 0.0;
              }
            } else if (pinning) {
              for (auto iter = particles.subsetIter(
                       pinning->ranges,
                       MpmPinningForce<T, dim>::target_scratch_name());
                   iter; ++iter)
                corotated_input
                    .particles[static_cast<std::size_t>(iter.entryId())]
                    .pinning_a = static_cast<double>(iter.template get<0>().A);
            }
          }
          if (gpu_solid_device_newton_vectors_active) {
            GPU_SOLID_IMPLICIT::solveCorotatedPcgDeviceResidual3D(
                gpu_solid_pd_operator, corotated_input,
                static_cast<double>(relative_tolerance),
                static_cast<double>(Base::objective.linear_solver->tolerance),
                Base::objective.linear_solver->max_iterations, &pcg_stats);
            gpu_solid_pcg_static_ready = true;
            gpu_solid_device_newton_step_ready = true;
            ZIRAN_INFO("GPU solid implicit PCG: energy=CorotatedIsotropic",
                       " iterations=", pcg_stats.iterations,
                       " initial=", pcg_stats.initial_preconditioned_norm,
                       " final=", pcg_stats.final_preconditioned_norm,
                       " upload_ms=", pcg_stats.upload_ms,
                       " solve_ms=", pcg_stats.solve_ms,
                       " download_ms=", pcg_stats.download_ms,
                       " vectors=device");
            return true;
          }
          GPU_SOLID_IMPLICIT::solveCorotatedPcg3D(
              gpu_solid_pd_operator, corotated_input, host_rhs,
              static_cast<double>(relative_tolerance),
              static_cast<double>(Base::objective.linear_solver->tolerance),
              Base::objective.linear_solver->max_iterations, host_ddv,
              &pcg_stats);
          if (device_trial)
            gpu_solid_pcg_static_ready = true;
          if (std::getenv("ZIRAN_SOLID_GPU_PCG_ORACLE") != nullptr) {
            typename Base::TVStack probe_x(dim, Base::num_nodes);
            for (int n = 0; n < Base::num_nodes; ++n)
              for (int d = 0; d < dim; ++d)
                probe_x(d, n) = static_cast<T>(
                    (((n * 13 + d * 7 + 5) % 19) - 9) * 0.03125);
            Base::objective.project(probe_x);
            typename Base::TVStack cpu_y(dim, Base::num_nodes);
            Base::objective.multiply(probe_x, cpu_y);
            Base::objective.project(cpu_y);
            std::vector<double> host_x(static_cast<std::size_t>(3 * Base::num_nodes));
            for (int n = 0; n < Base::num_nodes; ++n)
              for (int d = 0; d < dim; ++d)
                host_x[static_cast<std::size_t>(3 * n + d)] = probe_x(d, n);
            std::vector<double> gpu_y;
            GPU_SOLID_IMPLICIT::PdOperatorStats operator_stats;
            GPU_SOLID_IMPLICIT::applyCorotatedMatrixFree3D(
                gpu_solid_pd_operator, corotated_input, host_x, gpu_y,
                &operator_stats);
            for (int n = 0; n < Base::num_nodes; ++n) {
              const double y0 = gpu_y[static_cast<std::size_t>(3 * n + 0)];
              const double y1 = gpu_y[static_cast<std::size_t>(3 * n + 1)];
              const double y2 = gpu_y[static_cast<std::size_t>(3 * n + 2)];
              for (int row = 0; row < 3; ++row)
                gpu_y[static_cast<std::size_t>(3 * n + row)] =
                    node_projection[static_cast<std::size_t>(n)](row, 0) * y0 +
                    node_projection[static_cast<std::size_t>(n)](row, 1) * y1 +
                    node_projection[static_cast<std::size_t>(n)](row, 2) * y2;
            }
            double max_abs = 0, cpu_l2 = 0, diff_l2 = 0;
            for (int n = 0; n < Base::num_nodes; ++n)
              for (int d = 0; d < dim; ++d) {
                const double cpu = static_cast<double>(cpu_y(d, n));
                const double diff = gpu_y[static_cast<std::size_t>(3 * n + d)] - cpu;
                max_abs = std::max(max_abs, std::abs(diff));
                cpu_l2 += cpu * cpu;
                diff_l2 += diff * diff;
              }
            ZIRAN_INFO("GPU solid Corotated PCG matrix oracle: max_abs=", max_abs,
                       " rel_l2=", std::sqrt(diff_l2 / std::max(cpu_l2, 1e-300)),
                       " apply_ms=", operator_stats.apply_ms);
          }
        }
        for (int n = 0; n < Base::num_nodes; ++n)
          for (int d = 0; d < dim; ++d)
            ddv(d, n) = static_cast<T>(host_ddv[static_cast<std::size_t>(3 * n + d)]);
        if (std::getenv("ZIRAN_SOLID_GPU_PCG_ORACLE") != nullptr) {
          typename Base::TVStack cpu_ddv(dim, Base::num_nodes);
          cpu_ddv.setZero();
          Base::objective.linear_solver->setRelativeTolerance(relative_tolerance);
          Base::objective.linear_solver->solve(
              Base::objective, cpu_ddv, rhs, Base::verbose);
          double max_abs = 0, cpu_l2 = 0, diff_l2 = 0;
          for (int n = 0; n < Base::num_nodes; ++n)
            for (int d = 0; d < dim; ++d) {
              const double cpu = static_cast<double>(cpu_ddv(d, n));
              const double diff = static_cast<double>(ddv(d, n)) - cpu;
              max_abs = std::max(max_abs, std::abs(diff));
              cpu_l2 += cpu * cpu;
              diff_l2 += diff * diff;
            }
          ZIRAN_INFO("GPU solid PCG oracle: max_abs=", max_abs,
                     " rel_l2=", std::sqrt(diff_l2 / std::max(cpu_l2, 1e-300)));
        }
        ZIRAN_INFO("GPU solid implicit PCG: energy=",
                   has_pd ? "PDIsotropic" :
                   (has_linear_corotated ? "LinearCorotated" : "CorotatedIsotropic"),
                   " iterations=", pcg_stats.iterations,
                   " initial=", pcg_stats.initial_preconditioned_norm,
                   " final=", pcg_stats.final_preconditioned_norm,
                   " upload_ms=", pcg_stats.upload_ms,
                   " solve_ms=", pcg_stats.solve_ms,
                   " download_ms=", pcg_stats.download_ms);
        return true;
      };
    } else {
      Base::objective.device_linear_solve = {};
    }
    if (gpu_solid_implicit_state && gpu_solid_implicit_pcg) {
      Base::objective.device_residual_norm = [this](T& residual_norm) {
        if (!gpu_solid_device_newton_vectors_active)
          return false;
        const TV& gravity = Base::gravity;
        residual_norm = static_cast<T>(
            GPU_SOLID_IMPLICIT::preparePdNewtonResidual3D(
                gpu_solid_pd_operator,
                {static_cast<double>(gravity[0]),
                 static_cast<double>(gravity[1]),
                 static_cast<double>(gravity[2])},
                static_cast<double>(Base::dt)));
        return true;
      };
      Base::objective.device_step_commit = [this]() {
        if (!gpu_solid_device_newton_vectors_active ||
            !gpu_solid_device_newton_step_ready)
          return false;
        GPU_SOLID_IMPLICIT::applyPdNewtonIncrement3D(gpu_solid_pd_operator);
        GPU_SOLID_IMPLICIT::PdTrialStateStats stats;
        if (gpu_solid_device_corotated_vectors_active) {
          GPU_SOLID_IMPLICIT::CorotatedTrialStateInput input;
          input.dx = static_cast<double>(Base::dx);
          input.dt = static_cast<double>(Base::dt);
          input.reuse_static = true;
          input.reuse_velocity = true;
          input.scatter_residual = true;
          input.download_node_residual = false;
          auto to_ghost_vec = [](const GPU_STAGE2::Vec3d& value) {
            return GPU_STAGE3A::Vec3d{value.x, value.y, value.z};
          };
          input.ghost_collision.outer_min =
              to_ghost_vec(gpu_box_shell_collision.outer_min);
          input.ghost_collision.outer_max =
              to_ghost_vec(gpu_box_shell_collision.outer_max);
          input.ghost_collision.inner_min =
              to_ghost_vec(gpu_box_shell_collision.inner_min);
          input.ghost_collision.inner_max =
              to_ghost_vec(gpu_box_shell_collision.inner_max);
          input.ghost_collision.hole_min =
              to_ghost_vec(gpu_box_shell_collision.hole_min);
          input.ghost_collision.hole_max =
              to_ghost_vec(gpu_box_shell_collision.hole_max);
          input.ghost_collision.has_hole =
              gpu_box_shell_collision.has_hole;
          input.ghost_collision.valid = gpu_box_shell_collision.valid;
          input.ghost_penalty =
              static_cast<double>(implicit_penalty_collision);
          GPU_SOLID_IMPLICIT::evaluateCorotatedTrialState3D(
              gpu_solid_pd_operator, input, gpu_solid_trial_output,
              gpu_solid_trial_corotated_hessian, &stats);
        } else {
          GPU_SOLID_IMPLICIT::PdTrialStateInput input;
          input.dx = static_cast<double>(Base::dx);
          input.dt = static_cast<double>(Base::dt);
          input.enable_tl_contact = Base::force->lagrangian_contact != nullptr;
          input.reuse_static = true;
          input.reuse_velocity = true;
          input.scatter_residual = true;
          input.download_node_residual = false;
          GPU_SOLID_IMPLICIT::evaluatePdTrialState3D(
              gpu_solid_pd_operator, input, gpu_solid_trial_output, &stats);
        }
        gpu_solid_trial_device_tangent_ready = true;
        gpu_solid_trial_grad_velocity_deferred = true;
        gpu_solid_device_newton_step_ready = false;
        if (std::getenv("ZIRAN_SOLID_GPU_STATE_LOG") != nullptr)
          ZIRAN_INFO("GPU solid PD trial state: particles=", particles.count,
                     " tl_contact_particles=", stats.active_tl_contacts,
                     " upload_ms=", stats.upload_ms,
                     " gather_ms=", stats.gather_ms,
                     " contact_ms=", stats.contact_ms,
                     " download_ms=", stats.download_ms,
                     " vectors=device");
        return true;
      };
      Base::objective.device_line_search_commit =
          [this](T previous_energy, T& accepted_energy,
                 T& accepted_step) {
            if (!Base::newton.linesearch || !gpu_solid_device_grid_active ||
                !gpu_solid_device_newton_vectors_active ||
                !gpu_solid_device_newton_step_ready)
              return false;
            const TV& gravity = Base::gravity;
            const GPU_STAGE3A::Vec3d device_gravity{
                static_cast<double>(gravity[0]),
                static_cast<double>(gravity[1]),
                static_cast<double>(gravity[2])};
            double step = 1.0;
            double energy = 0.0;
            GPU_SOLID_IMPLICIT::PdTrialStateStats stats;
            do {
              GPU_SOLID_IMPLICIT::setPdNewtonLineSearchTrial3D(
                  gpu_solid_pd_operator, step);
              if (gpu_solid_device_corotated_vectors_active) {
                GPU_SOLID_IMPLICIT::CorotatedTrialStateInput input;
                input.dx = static_cast<double>(Base::dx);
                input.dt = static_cast<double>(Base::dt);
                input.reuse_static = true;
                input.reuse_velocity = true;
                input.scatter_residual = true;
                input.download_node_residual = false;
                auto to_ghost_vec = [](const GPU_STAGE2::Vec3d& value) {
                  return GPU_STAGE3A::Vec3d{value.x, value.y, value.z};
                };
                input.ghost_collision.outer_min =
                    to_ghost_vec(gpu_box_shell_collision.outer_min);
                input.ghost_collision.outer_max =
                    to_ghost_vec(gpu_box_shell_collision.outer_max);
                input.ghost_collision.inner_min =
                    to_ghost_vec(gpu_box_shell_collision.inner_min);
                input.ghost_collision.inner_max =
                    to_ghost_vec(gpu_box_shell_collision.inner_max);
                input.ghost_collision.hole_min =
                    to_ghost_vec(gpu_box_shell_collision.hole_min);
                input.ghost_collision.hole_max =
                    to_ghost_vec(gpu_box_shell_collision.hole_max);
                input.ghost_collision.has_hole =
                    gpu_box_shell_collision.has_hole;
                input.ghost_collision.valid =
                    gpu_box_shell_collision.valid;
                input.ghost_penalty =
                    static_cast<double>(implicit_penalty_collision);
                GPU_SOLID_IMPLICIT::evaluateCorotatedTrialState3D(
                    gpu_solid_pd_operator, input, gpu_solid_trial_output,
                    gpu_solid_trial_corotated_hessian, &stats);
              } else {
                GPU_SOLID_IMPLICIT::PdTrialStateInput input;
                input.dx = static_cast<double>(Base::dx);
                input.dt = static_cast<double>(Base::dt);
                input.enable_tl_contact = false;
                input.reuse_static = true;
                input.reuse_velocity = true;
                input.scatter_residual = true;
                input.download_node_residual = false;
                GPU_SOLID_IMPLICIT::evaluatePdTrialState3D(
                    gpu_solid_pd_operator, input, gpu_solid_trial_output,
                    &stats);
              }
              gpu_solid_trial_force_energy =
                  gpu_solid_trial_output.force_energy;
              gpu_solid_trial_force_energy_valid = true;
              energy = GPU_SOLID_IMPLICIT::computePdNewtonTotalEnergy3D(
                  gpu_solid_pd_operator, device_gravity,
                  static_cast<double>(Base::dt), step);
              if (energy <= static_cast<double>(previous_energy))
                break;
              step *= 0.5;
            } while (true);
            GPU_SOLID_IMPLICIT::commitPdNewtonLineSearchTrial3D(
                gpu_solid_pd_operator, step);
            gpu_solid_trial_device_tangent_ready = true;
            gpu_solid_trial_grad_velocity_deferred = true;
            gpu_solid_device_newton_step_ready = false;
            accepted_energy = static_cast<T>(energy);
            accepted_step = static_cast<T>(step);
            if (std::getenv("ZIRAN_SOLID_GPU_STATE_LOG") != nullptr)
              ZIRAN_INFO("GPU solid device line search: energy=",
                         gpu_solid_device_corotated_vectors_active
                             ? "CorotatedIsotropic" : "PDIsotropic",
                         " step=", step,
                         " total_energy=", energy,
                         " upload_ms=", stats.upload_ms,
                         " gather_ms=", stats.gather_ms,
                         " download_ms=", stats.download_ms);
            return true;
          };
    } else {
      Base::objective.device_residual_norm = {};
      Base::objective.device_step_commit = {};
      Base::objective.device_line_search_commit = {};
    }
    if (gpu_solid_implicit_state && gpu_solid_implicit_pcg) {
      Base::objective.device_state_finalize = [this]() {
        if (gpu_solid_device_resident &&
            gpu_solid_trial_device_tangent_ready &&
            gpu_solid_p2g_node_map.size ==
                static_cast<std::size_t>(Base::num_nodes)) {
          GPU_SOLID_IMPLICIT::exportFinalGridVelocityToNodeMap3D(
              gpu_solid_pd_operator, gpu_solid_p2g_node_map);
          gpu_solid_final_grid_device_ready = true;
          gpu_solid_p2g_indices_ready = true;
          ZIRAN_INFO("Solid converged grid velocity exported device-to-device: "
                     "nodes=", Base::num_nodes);
        }
        if (!gpu_solid_trial_grad_velocity_deferred)
          return;
        if (gpu_solid_device_resident &&
            GPU_STAGE3A::persistentSolidParticleStateValid(
                gpu_solid_particle_state,
                static_cast<std::size_t>(particles.count))) {
          // The converged grid velocity is already in the resident Q2 map.
          // The following device G2P recomputes gradV, so neither the Newton
          // increment nor this transient gradV needs a compatibility download.
          gpu_solid_trial_grad_velocity_deferred = false;
          gpu_solid_device_newton_vectors_active = false;
          gpu_solid_device_corotated_vectors_active = false;
          gpu_solid_device_newton_step_ready = false;
          ZIRAN_INFO("Solid final Newton vectors and trial gradV remain "
                     "device-resident");
          return;
        }
        ZIRAN_NAMED_TIMER("gpuSolidFinalGradVDownload");
        const auto begin = std::chrono::high_resolution_clock::now();
        std::vector<double> final_velocity_increment;
        if (gpu_solid_device_newton_vectors_active) {
          GPU_SOLID_IMPLICIT::downloadPdNewtonState3D(
              gpu_solid_pd_operator, final_velocity_increment,
              gpu_solid_trial_output.particle_grad_velocity);
          ZIRAN_ASSERT(final_velocity_increment.size() ==
                           static_cast<std::size_t>(3 * Base::num_nodes),
                       "GPU solid final dv size mismatch");
          tbb::parallel_for(0, Base::num_nodes, [&](int n) {
            for (int d = 0; d < dim; ++d)
              Base::dv(d, n) = static_cast<T>(
                  final_velocity_increment[static_cast<std::size_t>(3 * n + d)]);
          });
        } else {
          GPU_SOLID_IMPLICIT::downloadPdTrialGradVelocity3D(
              gpu_solid_pd_operator,
              gpu_solid_trial_output.particle_grad_velocity);
        }
        ZIRAN_ASSERT(gpu_solid_trial_output.particle_grad_velocity.size() ==
                         static_cast<std::size_t>(9 * particles.count),
                     "GPU solid final gradV size mismatch");
        tbb::parallel_for(0, particles.count, [&](int p) {
          for (int row = 0; row < dim; ++row)
            for (int col = 0; col < dim; ++col)
              Base::scratch_gradV[p](row, col) = static_cast<T>(
                  gpu_solid_trial_output.particle_grad_velocity[
                      static_cast<std::size_t>(9 * p + 3 * row + col)]);
        });
        gpu_solid_trial_grad_velocity_deferred = false;
        gpu_solid_device_newton_vectors_active = false;
        gpu_solid_device_corotated_vectors_active = false;
        gpu_solid_device_newton_step_ready = false;
        if (std::getenv("ZIRAN_SOLID_GPU_STATE_LOG") != nullptr) {
          const auto end = std::chrono::high_resolution_clock::now();
          ZIRAN_INFO("GPU solid final gradV D2H: particles=", particles.count,
                     " download_ms=",
                     std::chrono::duration<double, std::milli>(end - begin).count());
        }
      };
    } else {
      Base::objective.device_state_finalize = {};
    }
    if (gpu_solid_implicit_state && gpu_solid_implicit_pcg) {
      // Consume the device-scattered material force residual (node.idx order),
      // replacing the CPU force raster. Gravity and inertia stay on the host.
      Base::objective.device_residual_force =
          [this](typename Base::TVStack& residual) {
            if (gpu_solid_trial_output.node_residual.size() !=
                static_cast<std::size_t>(3 * Base::num_nodes))
              return false;
            tbb::parallel_for(0, Base::num_nodes, [&](int n) {
              for (int d = 0; d < dim; ++d)
                residual(d, n) += static_cast<T>(
                    gpu_solid_trial_output.node_residual[3 * n + d]);
            });
            return true;
          };
    } else {
      Base::objective.device_residual_force = {};
    }
    if (gpu_solid_implicit_probe && !gpu_solid_implicit_probe_callback_installed) {
      Base::general_callbacks.emplace_back([this](int, int event) {
        if (event != Base::BeforeNewtonSolve)
          return;
        if constexpr (dim != 3)
          return;
        if (!particles.exist(
                MaterialForce::template f_constitutive_model_name<PDIsotropic<T, dim>>()))
          return;
        Base::objective.updateStateForDv(Base::dv);
        GPU_SOLID_IMPLICIT::PdOperatorInput input;
        input.dx = static_cast<double>(Base::dx);
        input.dt = static_cast<double>(Base::dt);
        input.nodes.reserve(static_cast<std::size_t>(Base::num_nodes));
        Base::grid.iterateGridSerial([&](IV node, GridState<T, dim>& g) {
          input.nodes.push_back(GPU_SOLID_IMPLICIT::SolidNode{
              GPU_STAGE3A::packGridKey3D(node[0], node[1], node[2]),
              static_cast<int>(g.idx), static_cast<double>(g.m)});
        });
        const auto* model = particles.DataManager::getPointer(
            MaterialForce::template f_constitutive_model_name<PDIsotropic<T, dim>>());
        const auto* volume = particles.DataManager::getPointer(element_measure_name<T>());
        // updateStateForDv() above has populated this exact linearization cache;
        // use it for the oracle.  In particular, the target array is sparse by
        // range and must not be indexed as though every particle were pinned.
        const auto* pinning = particles.DataManager::getPointer(
            MpmPinningForce<T, dim>::target_scratch_name());
        std::size_t pinned_particle_count = 0;
        double max_pinning_a = 0;
        input.particles.resize(static_cast<std::size_t>(particles.count));
        for (int p = 0; p < particles.count; ++p) {
          const TV& x = particles.X.array[p];
          input.particles[static_cast<std::size_t>(p)] =
              GPU_SOLID_IMPLICIT::PdParticle{
                  GPU_STAGE3A::Vec3d{static_cast<double>(x[0]),
                                     static_cast<double>(x[1]),
                                     static_cast<double>(x[2])},
                  static_cast<double>((*volume)[p]),
                  static_cast<double>((*model)[p].mu), 0};
        }
        // PinningTargetScratch is sparse: accessing it outside `ranges` reads
        // uninitialized storage (and may trap with floating-point exceptions).
        // Populate only the entries owned by the helper.
        for (auto iter = particles.subsetIter(
                 pinning->ranges,
                 MpmPinningForce<T, dim>::target_scratch_name()); iter;
             ++iter) {
          const int p = iter.entryId();
          const double a = static_cast<double>(iter.template get<0>().A);
          input.particles[static_cast<std::size_t>(p)].pinning_a = a;
          if (a != 0) {
            ++pinned_particle_count;
            max_pinning_a = std::max(max_pinning_a, std::abs(a));
          }
        }
        typename Base::TVStack probe_x(dim, Base::num_nodes);
        for (int n = 0; n < Base::num_nodes; ++n)
          for (int d = 0; d < dim; ++d)
            probe_x(d, n) = static_cast<T>((((n * 13 + d * 7 + 5) % 19) - 9) * 0.03125);
        typename Base::TVStack cpu_y(dim, Base::num_nodes);
        Base::objective.multiply(probe_x, cpu_y);
        std::vector<double> host_x(static_cast<std::size_t>(Base::num_nodes * dim));
        for (int n = 0; n < Base::num_nodes; ++n)
          for (int d = 0; d < dim; ++d)
            host_x[static_cast<std::size_t>(3 * n + d)] = probe_x(d, n);
        std::vector<double> gpu_y;
        GPU_SOLID_IMPLICIT::PdOperatorStats gpu_stats;
        GPU_SOLID_IMPLICIT::applyPdMatrixFree3D(
            gpu_solid_pd_operator, input, host_x, gpu_y, &gpu_stats);
        double max_abs = 0, cpu_norm_sq = 0, diff_norm_sq = 0;
        for (int n = 0; n < Base::num_nodes; ++n)
          for (int d = 0; d < dim; ++d) {
            const double cpu = static_cast<double>(cpu_y(d, n));
            const double diff = gpu_y[static_cast<std::size_t>(3 * n + d)] - cpu;
            max_abs = std::max(max_abs, std::abs(diff));
            cpu_norm_sq += cpu * cpu;
            diff_norm_sq += diff * diff;
          }
        ZIRAN_INFO("GPU solid PD operator probe: nodes=", input.nodes.size(),
                   " particles=", input.particles.size(), " pinned=", pinned_particle_count,
                   " pinning_a_max=", max_pinning_a, " max_abs=", max_abs,
                   " rel_l2=", std::sqrt(diff_norm_sq / std::max(cpu_norm_sq, 1e-300)),
                   " upload_ms=", gpu_stats.upload_ms, " apply_ms=", gpu_stats.apply_ms,
                   " download_ms=", gpu_stats.download_ms);
      });
      gpu_solid_implicit_probe_callback_installed = true;
    }
  }

  void gridUpdate() {
    ZIRAN_TIMER();
    if (category == MATERIAL_PHASE_FLUID) {
      grid.iterateGrid([&](IV node, GridState<T, dim> &g) { g.new_v = g.v; });
      return;
    }
    setupSolidDeviceCallbacks();
    TV tmp = Base::gravity;
    Base::gravity = TV::Zero();
    if (Base::symplectic) {
      Base::gridVelocityExplicitUpdate(Base::dt);
    } else {
      Base::backwardEulerStep();
    }
    Base::gravity = tmp;
  }

