  void synchronizeFluidCompatibilityForHostOutput() {
#ifdef ENABLE_CUDA_STAGE2_PROBE
    if constexpr (dim == 3) {
      if (category == MATERIAL_PHASE_FLUID &&
          gpu_interface_solid_search && solid_normals.empty()) {
        std::vector<GPU_STAGE2::Vec3d> solid_x;
        std::vector<GPU_STAGE2::Vec3d> solid_normal;
        GPU_STAGE2::copyPersistentSpatialSearchFieldsToHost3D(
            *gpu_interface_solid_search, solid_x, solid_normal,
            !gpu_skip_interface_neighbor_search);
        solid_cur_positions.resize(solid_x.size());
        solid_normals.resize(solid_normal.size());
        tbb::parallel_for(std::size_t{0}, solid_x.size(),
            [&](std::size_t i) {
              solid_cur_positions[i] = TV(static_cast<T>(solid_x[i].x),
                  static_cast<T>(solid_x[i].y),
                  static_cast<T>(solid_x[i].z));
              solid_normals[i] = TV(static_cast<T>(solid_normal[i].x),
                  static_cast<T>(solid_normal[i].y),
                  static_cast<T>(solid_normal[i].z));
            });
        ZIRAN_INFO("Fluid solid-normal output sync: samples=", solid_x.size(),
            " bytes=", solid_x.size() * 2 * sizeof(GPU_STAGE2::Vec3d));
      }
      if (category == MATERIAL_PHASE_FLUID &&
          gpu_fluid_analytic_device_view.face_count != 0 &&
          quadrature_state.face_GQ.size() !=
              gpu_fluid_analytic_device_view.face_count) {
        std::vector<GPU_STAGE2::Vec3d> face_xq;
        std::vector<GPU_STAGE2::Vec3d> face_normal;
        GPU_STAGE2::copyFluidAnalyticFaceFieldsToHost3D(
            gpu_fluid_analytic, face_xq, face_normal);
        ZIRAN_ASSERT(face_xq.size() == face_normal.size(),
            "fluid analytic face output synchronization is incomplete");
        quadrature_state.face_GQ.resize(face_xq.size());
        quadrature_state.face_N.resize(face_normal.size());
        tbb::parallel_for(std::size_t{0}, face_xq.size(),
            [&](std::size_t i) {
              quadrature_state.face_GQ[i] = TV(static_cast<T>(face_xq[i].x),
                  static_cast<T>(face_xq[i].y),
                  static_cast<T>(face_xq[i].z));
              quadrature_state.face_N[i] = TV(
                  static_cast<T>(face_normal[i].x),
                  static_cast<T>(face_normal[i].y),
                  static_cast<T>(face_normal[i].z));
            });
        ZIRAN_INFO("Fluid analytic face output sync: samples=",
            face_xq.size(), " bytes=",
            face_xq.size() * 2 * sizeof(GPU_STAGE2::Vec3d));
      }
      if (category != MATERIAL_PHASE_FLUID ||
          gpu_velocity_transfer_device.size !=
              static_cast<std::size_t>(particles.count))
        return;
      const bool synchronize_x =
          !gpu_velocity_transfer_host_x_valid &&
          gpu_velocity_transfer_device_x_valid &&
          gpu_velocity_transfer_device.x != nullptr;
      const bool synchronize_v =
          !gpu_velocity_transfer_host_v_valid &&
          gpu_velocity_transfer_device_v_grad_valid &&
          gpu_velocity_transfer_device.v != nullptr;
      const bool synchronize_grad_v =
          !gpu_velocity_transfer_host_grad_v_valid &&
          gpu_velocity_transfer_device_v_grad_valid &&
          gpu_velocity_transfer_device.grad_v != nullptr;
      const bool synchronize_pressure =
          !gpu_velocity_transfer_host_pressure_valid &&
          gpu_velocity_transfer_device.pressure != nullptr;
      if (!synchronize_x && !synchronize_v &&
          !synchronize_grad_v && !synchronize_pressure)
        return;
      GPU_STAGE2::VelocityTransferDownloadMask mask;
      mask.x = synchronize_x;
      mask.v = synchronize_v;
      mask.grad_v = synchronize_grad_v;
      mask.pressure = synchronize_pressure;
      GPU_STAGE2::VelocityTransferHostView host;
      GPU_STAGE2::VelocityTransferDownloadStats stats;
      GPU_STAGE2::downloadFluidVelocityTransferDeviceView3D(
          gpu_velocity_transfer, gpu_velocity_transfer_device,
          mask, host, &stats);
      ZIRAN_ASSERT(host.size ==
              static_cast<std::size_t>(particles.count),
          "fluid output synchronization is incomplete");
      if (synchronize_x) {
        ZIRAN_ASSERT(host.x,
            "fluid X output synchronization is incomplete");
        tbb::parallel_for(0, particles.count, [&](int p) {
          const auto& x = host.x[static_cast<std::size_t>(p)];
          particles.X.array[p] = TV(static_cast<T>(x.x),
                                    static_cast<T>(x.y),
                                    static_cast<T>(x.z));
        });
        gpu_velocity_transfer_host_x_valid = true;
      }
      if (synchronize_v) {
        ZIRAN_ASSERT(host.v,
            "fluid V output synchronization is incomplete");
        tbb::parallel_for(0, particles.count, [&](int p) {
          const auto& v = host.v[static_cast<std::size_t>(p)];
          particles.V.array[p] = TV(static_cast<T>(v.x),
                                    static_cast<T>(v.y),
                                    static_cast<T>(v.z));
        });
        gpu_velocity_transfer_host_v_valid = true;
      }
      if (synchronize_grad_v) {
        ZIRAN_ASSERT(host.grad_v,
            "fluid gradV output synchronization is incomplete");
        tbb::parallel_for(0, particles.count, [&](int p) {
          const auto& grad = host.grad_v[static_cast<std::size_t>(p)];
          for (int col = 0; col < 3; ++col)
            for (int row = 0; row < 3; ++row)
              Base::scratch_gradV[p](row, col) =
                  static_cast<T>(grad.values[row + 3 * col]);
        });
        gpu_velocity_transfer_host_grad_v_valid = true;
      }
      if (synchronize_pressure) {
        ZIRAN_ASSERT(host.pressure,
            "fluid pressure output synchronization is incomplete");
        auto* J_pointer = particles.DataManager::getPointer(J_name<T>());
        ZIRAN_ASSERT(J_pointer,
            "fluid pressure output requires the particle J field");
        override_J.resize(particles.count);
        tbb::parallel_for(0, particles.count, [&](int p) {
          const T pressure = static_cast<T>(
              host.pressure[static_cast<std::size_t>(p)]);
          (*J_pointer)[p] = pressure;
          override_J[p] = pressure;
        });
        gpu_velocity_transfer_host_pressure_valid = true;
      }
      ZIRAN_INFO("Fluid device compatibility output sync: particles=",
          stats.particles, " bytes=", stats.bytes,
          " x=", synchronize_x ? 1 : 0,
          " v=", synchronize_v ? 1 : 0,
          " grad_v=", synchronize_grad_v ? 1 : 0,
          " pressure=", synchronize_pressure ? 1 : 0,
          " download_ms=", stats.download_ms);
    }
#endif
  }

