  void addBoundarySpring() {
    gpu_solid_device_ghost_contact_active = false;
    gpu_solid_device_ordinary_pinning_active = false;
    auto *pin_pointer = particles.DataManager::getPointer(
        MpmMultiTargetPinningForce<T, dim>::target_name());
    // if (pin_pointer->size() < (size_t)particles.count) {
    //   pin_pointer->resize(particles.count);
    // }
    if (pin_pointer == nullptr)
      return;
    const bool has_dynamic_contact_object = std::any_of(
        Base::collision_objects.begin(), Base::collision_objects.end(),
        [](const auto& object) {
          return object->type == AnalyticCollisionObject<T, dim>::GHOST ||
              object->type == AnalyticCollisionObject<T, dim>::STICKY;
        });
    const bool host_pinning_needs_current_x =
        Base::force && (Base::force->pinning ||
            (Base::force->multi_target_pinning &&
             !Base::force->multi_target_pinning->collider_spring));
    if (!has_dynamic_contact_object && !host_pinning_needs_current_x)
      return;
    if (!has_dynamic_contact_object && canUseResidentSolidOrdinaryPinning()) {
      gpu_solid_device_ordinary_pinning_active = true;
      ZIRAN_INFO("Solid ordinary pinning coefficients remain device-resident");
      if (Base::force && Base::force->lagrangian_contact)
        ZIRAN_INFO("Solid TL self-contact remains device-resident");
      return;
    }
    if (canUseResidentSolidGhostContact()) {
      gpu_solid_device_ghost_contact_active = true;
      ZIRAN_INFO("Solid resident GHOST contact targets remain device-resident");
      gpu_solid_device_ordinary_pinning_active =
          canUseResidentSolidOrdinaryPinning();
      if (gpu_solid_device_ordinary_pinning_active)
        ZIRAN_INFO("Solid ordinary pinning coefficients remain device-resident");
      return;
    }
    synchronizeSolidCurrentXForHostContact();
    before_advect = particles.X.array;
    tbb::parallel_for(0, particles.count, [&](int i) {
      (*pin_pointer)[i].x.clear();
      (*pin_pointer)[i].v.clear();
      (*pin_pointer)[i].k = 0;
    });
    // addSpringWithSolid(another_sim);
    auto *config_scheme =
        particles.DataManager::getPointer(config_scheme_name());
    auto *X0 = particles.DataManager::getPointer(X0_name<TV>());
    tbb::parallel_for(0, particles.count, [&](int i) {
      // TV& Xp = particles.X.array[i];
      TV &Xp = (Base::config_scheme != CONFIG_UPDATE_LAGRANGIAN)
                   ? (*X0)[i]
                   : particles.X.array[i];
      TV &Vp = particles.V.array[i];
      // TV& Xp = (*X0)[i];
      for (int k = 0; k < (int)Base::collision_objects.size(); ++k) {
        T phi;
        TV n;
        if (Base::collision_objects[k]->type == AnalyticCollisionObject<T, dim>::GHOST){
            // continue;
          bool collided = Base::collision_objects[k]->queryInside(Xp, phi, n, 0);
          if (collided) {
            TV Xs = Xp - phi * n;
            (*pin_pointer)[i].x.push_back(Xs);
            (*pin_pointer)[i].v.push_back(TV::Zero());
            (*pin_pointer)[i].k = implicit_penalty_collision;
          }
        }
        else if (Base::collision_objects[k]->type == AnalyticCollisionObject<T, dim>::STICKY){
          bool collided = Base::collision_objects[k]->queryInside(Xp, phi, n, 0);
          if (collided) {
            TV Xs = Xp - phi * n;
            // Vp = Vp.dot(n) * n + 0.0 * (Vp - Vp.dot(n) * n);
            (*pin_pointer)[i].x.push_back(Xs);
            (*pin_pointer)[i].v.push_back(TV::Zero());
            (*pin_pointer)[i].k = implicit_penalty_collision;
          }
        }
      }
    });
  }

