  bool canUseResidentSolidGhostContact() {
#ifdef ENABLE_CUDA_STAGE2_PROBE
    if constexpr (dim == 3) {
      if (category != MATERIAL_PHASE_SOLID || !gpu_solid_device_resident ||
          !gpu_solid_implicit_state || !gpu_solid_implicit_pcg ||
          !gpu_box_shell_collision.valid || !Base::force ||
          !Base::force->multi_target_pinning ||
          !Base::force->multi_target_pinning->collider_spring ||
          Base::force->lagrangian_contact ||
          Base::collision_objects.size() != 1 ||
          Base::collision_objects.front()->type !=
              AnalyticCollisionObject<T, dim>::GHOST ||
          std::getenv("ZIRAN_SOLID_GPU_STATE_ORACLE") != nullptr ||
          std::getenv("ZIRAN_SOLID_GPU_PCG_ORACLE") != nullptr ||
          std::getenv("ZIRAN_SOLID_GHOST_CONTACT_PROBE") != nullptr ||
          !GPU_STAGE3A::persistentSolidParticleStateValid(
              gpu_solid_particle_state,
              static_cast<std::size_t>(particles.count)))
        return false;
      const auto* model = particles.DataManager::getPointer(
          MaterialForce::template f_constitutive_model_name<
              CorotatedIsotropic<T, dim>>());
      if (!model)
        return false;
      if (Base::force->pinning &&
          !canUseResidentSolidOrdinaryPinning())
        return false;
      for (int p = 0; p < particles.count; ++p)
        if (!(*model)[p].project)
          return false;
      return true;
    }
#endif
    return false;
  }

  bool canUseResidentSolidOrdinaryPinning() {
#ifdef ENABLE_CUDA_STAGE2_PROBE
    if constexpr (dim == 3) {
      if (category != MATERIAL_PHASE_SOLID || !gpu_solid_device_resident ||
          !gpu_solid_implicit_state || !gpu_solid_implicit_pcg ||
          Base::config_scheme != CONFIG_TOTAL_LAGRANGIAN || !Base::force ||
          !Base::force->pinning ||
          (Base::force->multi_target_pinning &&
           !Base::force->multi_target_pinning->collider_spring) ||
          std::getenv("ZIRAN_SOLID_GPU_STATE_ORACLE") != nullptr ||
          std::getenv("ZIRAN_SOLID_GPU_PCG_ORACLE") != nullptr ||
          !GPU_STAGE3A::persistentSolidParticleStateValid(
              gpu_solid_particle_state,
              static_cast<std::size_t>(particles.count)))
        return false;
      const bool has_pd = particles.exist(
          MaterialForce::template f_constitutive_model_name<
              PDIsotropic<T, dim>>());
      const bool has_corotated = particles.exist(
          MaterialForce::template f_constitutive_model_name<
              CorotatedIsotropic<T, dim>>());
      return (has_pd || has_corotated) &&
          (!Base::force->lagrangian_contact ||
           (has_pd && !Base::newton.linesearch));
    }
#endif
    return false;
  }

