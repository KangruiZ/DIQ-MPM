  template <int degree> void buildWMatrix(MpmGrid<T, dim, degree> &gridv) {
    ZIRAN_TIMER();
    MpmGrid<T, dim, aod> grid6;
    grid6.activatePages(interface_GQ, Base::dx, 0, 1, -TV::Ones() * Base::dx * 0.5);
    for (auto &Xp : interface_GQ) {
      BSplineWeights<T, dim, aod> spline6(Xp - TV::Ones() * Base::dx * 0.5,
                                          Base::dx);
      uint64_t offset6 =
          Base::SparseMask::Linear_Offset(to_std_array(spline6.base_node));
      grid6.iterateKernel(
          spline6, offset6,
          [&](IV node6, T w6, TV dw6, GridState<T, dim> &g6) { g6.m += w6; });
    }
    W = Eigen::SparseMatrix<T>(grid6.getNumNodes(), gridv.getNumNodes() * dim);

    std::vector<Eigen::Triplet<T>> W_tri(
        interface_GQ.size() * gridv.kernel_size * grid6.kernel_size * dim);
    tbb::parallel_for(0, (int)interface_GQ.size(), [&](int i) {
      // TV Xp_rest = interface_GQ[i];
      TV Xp_rest = (category == MATERIAL_PHASE_SOLID &&
                    Base::config_scheme != CONFIG_UPDATE_LAGRANGIAN)
                       ? interface_rest_GQ[i]
                       : interface_GQ[i];
      TV Xp_cur = interface_GQ[i];
      TV normal = interface_N[i];
      T len = interface_L[i];
      BSplineWeights<T, dim, degree> splinev(
          degree == 2 ? Xp_rest : (Xp_rest - TV::Ones() * Base::dx * 0.5),
          Base::dx);
      BSplineWeights<T, dim, aod> spline6(Xp_cur - TV::Ones() * Base::dx * 0.5,
                                          Base::dx);
      uint64_t offsetv =
          Base::SparseMask::Linear_Offset(to_std_array(splinev.base_node));
      uint64_t offset6 =
          Base::SparseMask::Linear_Offset(to_std_array(spline6.base_node));
      int cnt = i * gridv.kernel_size * grid6.kernel_size * dim;
      gridv.iterateKernel(
          splinev, offsetv, [&](IV nodev, T wv, TV dwv, GridState<T, dim> &gv) {
            int idxv = gv.idx;
            if (idxv < 0)
              return;
            grid6.iterateKernel(
                spline6, offset6,
                [&](IV node6, T w6, TV dw6, GridState<T, dim> &g6) {
                  int idx6 = g6.idx;
                  if (idx6 < 0)
                    return;
                  for (int alpha = 0; alpha < dim; ++alpha)
                    W_tri[cnt++] =
                        Eigen::Triplet<T>(idx6, idxv * dim + alpha,
                                          len * wv * w6 * normal[alpha]);
                });
          });
    });
    W.setFromTriplets(W_tri.begin(), W_tri.end());
  }

  bool buildDeviceInterfaceW(int velocity_degree,
                             bool shift_velocity_half_dx) {
#ifdef ENABLE_CUDA_STAGE2_PROBE
    if constexpr (dim == 3) {
      if (std::getenv("ZIRAN_GPU_INTERFACE_W_DISABLE") != nullptr)
        return false;
      if (!gpu_device_assembly_valid ||
          gpu_velocity_node_map.size != static_cast<std::size_t>(num_v))
        return false;
      const bool compare_interface_w =
          std::getenv("ZIRAN_GPU_INTERFACE_FIELDS_COMPARE") != nullptr;
      const bool resident_interface_available =
          gpu_interface_quad_device_ready &&
          (!gpu_interface_quad_host_fields_valid ||
              gpu_interface_fields.size == interface_GQ.size());
      const bool resident_interface = resident_interface_available &&
          (!gpu_interface_quad_host_fields_valid || compare_interface_w);
      if (!resident_interface) {
        ZIRAN_ASSERT(interface_GQ.size() == interface_rest_GQ.size() &&
                         interface_GQ.size() == interface_N.size() &&
                         interface_GQ.size() == interface_L.size(),
                     "interface W field size mismatch");
      }
      GPU_STAGE3A::InterfaceWAssemblyInput3D input;
      input.dx = static_cast<double>(Base::dx);
      input.velocity_degree = velocity_degree;
      input.shift_velocity_half_dx = shift_velocity_half_dx;
      input.velocity_node_count = num_v;
      input.resident_velocity_nodes = gpu_velocity_node_map;
      const std::size_t count = resident_interface
          ? gpu_interface_fields.size : interface_GQ.size();
      if (resident_interface && count != 0) {
        input.resident_rest_x = category == MATERIAL_PHASE_SOLID
            ? gpu_interface_fields.rest_x : gpu_interface_fields.current_x;
        input.resident_current_x = gpu_interface_fields.current_x;
        input.resident_normal = gpu_interface_fields.normal;
        input.resident_length = gpu_interface_fields.length;
        input.resident_sample_count = count;
      } else if (!resident_interface) {
        input.rest_x.resize(count);
        input.current_x.resize(count);
        input.normal.resize(count);
        input.length.resize(count);
        tbb::parallel_for(std::size_t(0), count, [&](std::size_t i) {
          const TV& rest = category == MATERIAL_PHASE_SOLID
              ? interface_rest_GQ[i] : interface_GQ[i];
          const TV& current = interface_GQ[i];
          const TV& normal = interface_N[i];
          input.rest_x[i] = {static_cast<double>(rest[0]),
              static_cast<double>(rest[1]), static_cast<double>(rest[2])};
          input.current_x[i] = {static_cast<double>(current[0]),
              static_cast<double>(current[1]), static_cast<double>(current[2])};
          input.normal[i] = {static_cast<double>(normal[0]),
              static_cast<double>(normal[1]), static_cast<double>(normal[2])};
          input.length[i] = static_cast<double>(interface_L[i]);
        });
      }
      GPU_STAGE3A::assembleInterfaceW3DDevice(input, gpu_w);
      if (compare_interface_w && resident_interface) {
        std::vector<GPU_STAGE2::Vec3d> device_rest;
        std::vector<GPU_STAGE2::Vec3d> device_current;
        std::vector<GPU_STAGE2::Vec3d> device_normal;
        std::vector<double> device_length;
        GPU_STAGE2::copyInterfaceQuadratureFieldsToHost3D(
            gpu_interface_fields, device_rest, device_current,
            device_normal, device_length);
        double max_rest_field_error = 0.0;
        double max_current_field_error = 0.0;
        double max_normal_field_error = 0.0;
        double max_length_field_error = 0.0;
        for (std::size_t i = 0; i < count; ++i) {
          const TV& host_rest = category == MATERIAL_PHASE_SOLID
              ? interface_rest_GQ[i] : interface_GQ[i];
          const GPU_STAGE2::Vec3d& resident_rest =
              category == MATERIAL_PHASE_SOLID
              ? device_rest[i] : device_current[i];
          const double host_rest_values[3] = {
              static_cast<double>(host_rest[0]),
              static_cast<double>(host_rest[1]),
              static_cast<double>(host_rest[2])};
          const double resident_rest_values[3] = {
              resident_rest.x, resident_rest.y, resident_rest.z};
          const double host_current_values[3] = {
              static_cast<double>(interface_GQ[i][0]),
              static_cast<double>(interface_GQ[i][1]),
              static_cast<double>(interface_GQ[i][2])};
          const double resident_current_values[3] = {
              device_current[i].x, device_current[i].y,
              device_current[i].z};
          const double host_normal_values[3] = {
              static_cast<double>(interface_N[i][0]),
              static_cast<double>(interface_N[i][1]),
              static_cast<double>(interface_N[i][2])};
          const double resident_normal_values[3] = {
              device_normal[i].x, device_normal[i].y, device_normal[i].z};
          for (int d = 0; d < 3; ++d) {
            max_rest_field_error = std::max(max_rest_field_error,
                std::abs(host_rest_values[d] - resident_rest_values[d]));
            max_current_field_error = std::max(max_current_field_error,
                std::abs(host_current_values[d] -
                    resident_current_values[d]));
            max_normal_field_error = std::max(max_normal_field_error,
                std::abs(host_normal_values[d] -
                    resident_normal_values[d]));
          }
          max_length_field_error = std::max(max_length_field_error,
              std::abs(static_cast<double>(interface_L[i]) -
                  device_length[i]));
        }
        GPU_STAGE3A::InterfaceWAssemblyInput3D host_input;
        host_input.dx = input.dx;
        host_input.velocity_degree = input.velocity_degree;
        host_input.shift_velocity_half_dx = input.shift_velocity_half_dx;
        host_input.velocity_node_count = input.velocity_node_count;
        host_input.resident_velocity_nodes = input.resident_velocity_nodes;
        host_input.rest_x.resize(count);
        host_input.current_x.resize(count);
        host_input.normal.resize(count);
        host_input.length.resize(count);
        tbb::parallel_for(std::size_t(0), count, [&](std::size_t i) {
          const TV& rest = category == MATERIAL_PHASE_SOLID
              ? interface_rest_GQ[i] : interface_GQ[i];
          const TV& current = interface_GQ[i];
          const TV& normal = interface_N[i];
          host_input.rest_x[i] = {static_cast<double>(rest[0]),
              static_cast<double>(rest[1]), static_cast<double>(rest[2])};
          host_input.current_x[i] = {static_cast<double>(current[0]),
              static_cast<double>(current[1]), static_cast<double>(current[2])};
          host_input.normal[i] = {static_cast<double>(normal[0]),
              static_cast<double>(normal[1]), static_cast<double>(normal[2])};
          host_input.length[i] = static_cast<double>(interface_L[i]);
        });
        GPU_STAGE3A::DeviceCsrMatrix host_device_w;
        GPU_STAGE3A::assembleInterfaceW3DDevice(host_input, host_device_w);
        const GPU_STAGE3A::CsrMatrix resident_csr =
            GPU_STAGE3A::copyDeviceCsrToHost(gpu_w);
        const GPU_STAGE3A::CsrMatrix host_csr =
            GPU_STAGE3A::copyDeviceCsrToHost(host_device_w);
        const bool same_shape = resident_csr.rows == host_csr.rows &&
            resident_csr.cols == host_csr.cols &&
            resident_csr.row_offsets == host_csr.row_offsets &&
            resident_csr.col_indices == host_csr.col_indices &&
            resident_csr.values.size() == host_csr.values.size();
        double max_value_error = 0.0;
        if (same_shape)
          for (std::size_t i = 0; i < resident_csr.values.size(); ++i)
            max_value_error = std::max(max_value_error,
                std::abs(resident_csr.values[i] - host_csr.values[i]));
        ZIRAN_INFO("GPU interface W resident/host comparison: phase=",
            category, " same_shape=", same_shape ? 1 : 0,
            " resident_nnz=", resident_csr.values.size(),
            " host_nnz=", host_csr.values.size(),
            " max_value_error=", max_value_error,
            " max_rest_field_error=", max_rest_field_error,
            " max_current_field_error=", max_current_field_error,
            " max_normal_field_error=", max_normal_field_error,
            " max_length_field_error=", max_length_field_error);
      }
      gpu_w_valid = true;
      if (gpu_stage3b_validate_blocks) {
        const GPU_STAGE3A::CsrMatrix host_w =
            GPU_STAGE3A::copyDeviceCsrToHost(gpu_w);
        W = GPU_STAGE3A::makeEigenFromCsrLocal<T>(host_w);
      } else {
        W = Eigen::SparseMatrix<T>(gpu_w.rows, num_v * dim);
      }
      ZIRAN_INFO("GPU interface W assembly: phase=", category,
          " samples=", count, " rows=", gpu_w.rows,
          " cols=", gpu_w.cols, " nonzeros=", gpu_w.nonzeros,
          " velocity_degree=", velocity_degree);
      return true;
    }
#endif
    return false;
  }

  void buildWMatrixFromGpuSolidVelocity() {
    ZIRAN_TIMER();
    if constexpr (dim != 3) {
      ZIRAN_ASSERT(false, "GPU solid velocity interface assembly is 3D-only");
    } else {
      const std::vector<GPU_STAGE3A::AssemblyGridNode> velocity_nodes =
          GPU_STAGE3A::copyDeviceGridNodeMapToHost(gpu_velocity_node_map);
      MpmGrid<T, dim, aod> grid6;
      grid6.activatePages(interface_GQ, Base::dx, 0, 1,
                    -TV::Ones() * Base::dx * (T)0.5);
      for (const TV& Xp : interface_GQ) {
        BSplineWeights<T, dim, aod> spline6(
            Xp - TV::Ones() * Base::dx * (T)0.5, Base::dx);
        grid6[spline6.base_node].m += (T)1;
      }
      W = Eigen::SparseMatrix<T>(grid6.getNumNodes(), num_v * dim);
      std::vector<Eigen::Triplet<T>> triplets;
      triplets.reserve(interface_GQ.size() * 27 * dim);
      for (std::size_t q = 0; q < interface_GQ.size(); ++q) {
        BSplineWeights<T, dim, 2> splinev(interface_rest_GQ[q], Base::dx);
        BSplineWeights<T, dim, aod> spline6(
            interface_GQ[q] - TV::Ones() * Base::dx * (T)0.5, Base::dx);
        const int row = grid6[spline6.base_node].idx;
        for (int i = 0; i < 3; ++i)
          for (int j = 0; j < 3; ++j)
            for (int k = 0; k < 3; ++k) {
              const IV node = splinev.base_node + IV(i, j, k);
              const auto key = GPU_STAGE3A::packGridKey3D(
                  node[0], node[1], node[2]);
              const auto it = std::lower_bound(
                  velocity_nodes.begin(), velocity_nodes.end(), key,
                  [](const GPU_STAGE3A::AssemblyGridNode& entry,
                     GPU_STAGE3A::GridKey value) { return entry.key < value; });
              if (it == velocity_nodes.end() || it->key != key || it->idx < 0)
                continue;
              const T weight = splinev.w[0][i] * splinev.w[1][j] *
                  splinev.w[2][k];
              for (int alpha = 0; alpha < dim; ++alpha)
                triplets.emplace_back(row, it->idx * dim + alpha,
                    interface_L[q] * weight * interface_N[q][alpha]);
            }
      }
      W.setFromTriplets(triplets.begin(), triplets.end());
      ZIRAN_INFO("Host interface W A/B fallback: phase=", category,
          " samples=", interface_GQ.size(), " rows=", W.rows(),
          " nonzeros=", W.nonZeros());
    }
  }

  // The GPU fluid path does not populate the CPU Q1 grid.  Build the
  // interface matrix directly from the compact GPU velocity-node lookup so a
  // non-empty interface does not fall back to an empty/stale SPGrid.
  void buildWMatrixFromGpuVelocity() {
    ZIRAN_TIMER();
    if constexpr (dim != 3) {
      ZIRAN_ASSERT(false, "GPU velocity interface assembly is 3D-only");
      return;
    } else {
      MpmGrid<T, dim, aod> grid6;
      grid6.activatePages(interface_GQ, Base::dx, 0, 1,
                    -TV::Ones() * Base::dx * (T)0.5);
      for (const TV &Xp : interface_GQ) {
        BSplineWeights<T, dim, aod> spline6(Xp - TV::Ones() * Base::dx * (T)0.5,
                                            Base::dx);
        const uint64_t offset6 =
            Base::SparseMask::Linear_Offset(to_std_array(spline6.base_node));
        grid6.iterateKernel(
            spline6, offset6,
            [&](IV, T w6, TV, GridState<T, dim> &g6) { g6.m += w6; });
      }
      const int interface_dofs = grid6.getNumNodes();
      W = Eigen::SparseMatrix<T>(interface_dofs, num_v * dim);
      std::vector<Eigen::Triplet<T>> W_tri;
      W_tri.reserve(interface_GQ.size() * 8 * dim);
      const bool run_canonical_w_oracle =
          gpu_fluid_canonical_dof_order && gpu_canonical_dof_oracle_valid &&
          std::getenv("ZIRAN_GPU_FLUID_CANONICAL_DOF_ORACLE") != nullptr;
      std::vector<Eigen::Triplet<T>> legacy_W_tri;
      if (run_canonical_w_oracle)
        legacy_W_tri.reserve(interface_GQ.size() * 8 * dim);
      for (std::size_t i = 0; i < interface_GQ.size(); ++i) {
        const TV &Xp = interface_GQ[i];
        const TV &normal = interface_N[i];
        const T len = interface_L[i];
        BSplineWeights<T, dim, 1> splinev(Xp - TV::Ones() * Base::dx * (T)0.5,
                                          Base::dx);
        BSplineWeights<T, dim, aod> spline6(Xp - TV::Ones() * Base::dx * (T)0.5,
                                            Base::dx);
        const int idx6 = grid6[spline6.base_node].idx;
        if (idx6 < 0)
          continue;
        for (int x = 0; x < 2; ++x)
          for (int y = 0; y < 2; ++y)
            for (int z = 0; z < 2; ++z) {
              const IV node = splinev.base_node + IV(x, y, z);
              const auto key =
                  GPU_STAGE3A::packGridKey3D(node[0], node[1], node[2]);
              const auto it = std::lower_bound(
                  gpu_velocity_nodes.begin(), gpu_velocity_nodes.end(), key,
                  [](const GPU_STAGE3A::AssemblyGridNode &entry,
                     GPU_STAGE3A::GridKey value) { return entry.key < value; });
              if (it == gpu_velocity_nodes.end() || it->key != key ||
                  it->idx < 0)
                continue;
              const T wv = splinev.w[0][x] * splinev.w[1][y] * splinev.w[2][z];
              for (int alpha = 0; alpha < dim; ++alpha) {
                W_tri.emplace_back(idx6, it->idx * dim + alpha,
                                   len * wv * normal[alpha]);
                if (run_canonical_w_oracle) {
                  const int legacy_node = gpu_canonical_velocity_to_legacy.at(
                      static_cast<std::size_t>(it->idx));
                  legacy_W_tri.emplace_back(idx6, legacy_node * dim + alpha,
                                            len * wv * normal[alpha]);
                }
              }
            }
      }
      W.setFromTriplets(W_tri.begin(), W_tri.end());
      if (run_canonical_w_oracle) {
        Eigen::SparseMatrix<T> legacy_w(interface_dofs, num_v * dim);
        legacy_w.setFromTriplets(legacy_W_tri.begin(), legacy_W_tri.end());
        std::vector<Eigen::Triplet<T>> permuted_tri;
        permuted_tri.reserve(static_cast<std::size_t>(W.nonZeros()));
        for (int col = 0; col < W.outerSize(); ++col)
          for (typename Eigen::SparseMatrix<T>::InnerIterator it(W, col); it;
               ++it) {
            const int canonical_node = it.col() / dim;
            const int component = it.col() % dim;
            const int legacy_col = gpu_canonical_velocity_to_legacy.at(
                static_cast<std::size_t>(canonical_node)) * dim + component;
            permuted_tri.emplace_back(it.row(), legacy_col, it.value());
          }
        Eigen::SparseMatrix<T> permuted_w(interface_dofs, num_v * dim);
        permuted_w.setFromTriplets(permuted_tri.begin(), permuted_tri.end());
        const Eigen::SparseMatrix<T> difference = permuted_w - legacy_w;
        auto sparse_max_abs = [](const Eigen::SparseMatrix<T>& matrix) {
          T value = 0;
          for (int col = 0; col < matrix.outerSize(); ++col)
            for (typename Eigen::SparseMatrix<T>::InnerIterator it(matrix, col);
                 it; ++it)
              value = std::max(value, std::abs(it.value()));
          return value;
        };
        const T max_abs = sparse_max_abs(difference);
        const T max_ref = sparse_max_abs(legacy_w);
        ZIRAN_INFO("GPU canonical DOF oracle W: rows=", interface_dofs,
                   " nnz=", legacy_w.nonZeros(), " max_abs=", max_abs,
                   " max_rel=", max_abs / std::max(max_ref, (T)1e-30));
        ZIRAN_ASSERT(max_abs <= (T)1e-12 * std::max(max_ref, (T)1),
                     "canonical DOF oracle W value mismatch");
      }
    }
  }

  // M v + G p = a
  // D v + S p = b
  TStack solved_p, solved_v;
  int analytic_sample_condition_checking_serial_number;
  void solveSystem() {
    ZIRAN_TIMER();
    // `use_vp` builds the standalone solid Q2Q0 Schur complement
    //
    //     (S - D M^{-1} G) p = b - D M^{-1} a,  D = -G^T.
    //
    // It is intentionally separate from CouplingSimulation's larger KKT
    // system, but all five base blocks already have device-resident forms
    // after the Stage3B solid assembly.  Form the two sparse products and the
    // compact pressure CSR on CUDA, then either give it directly to AMGX or
    // use the existing AMGCL-CUDA compatibility solve.
    const bool use_gpu_vp_pressure =
        gpu_vp_pressure_system && gpu_device_assembly_valid;
    if (use_gpu_vp_pressure) {
      ZIRAN_NAMED_TIMER("gpuVpPressureSolve");
      const GPU_STAGE3A::DeviceCsrMatrix d_device =
          GPU_STAGE3A::transposeDeviceCsrMatrix(gpu_g, -1.0);
      const GPU_STAGE3A::DeviceCsrMatrix d_minv_device =
          GPU_STAGE3A::multiplyDeviceCsrMatrices(d_device, gpu_m_inv);
      const GPU_STAGE3A::DeviceCsrMatrix d_minv_g_device =
          GPU_STAGE3A::multiplyDeviceCsrMatrices(d_minv_device, gpu_g);
      const GPU_STAGE3A::DeviceCsrMatrix left_device =
          GPU_STAGE3A::assembleDeviceCsrBlocks(
              num_p, num_p,
              {{gpu_s, 0, 0, 1.0}, {d_minv_g_device, 0, 0, -1.0}});
      const GPU_STAGE3A::DeviceVector minv_a_device =
          GPU_STAGE3A::multiplyDeviceCsrVector(gpu_m_inv, gpu_a);
      const GPU_STAGE3A::DeviceVector d_minv_a_device =
          GPU_STAGE3A::multiplyDeviceCsrVector(d_device, minv_a_device);
      const GPU_STAGE3A::DeviceVector rhs_device =
          GPU_STAGE3A::addDeviceVectors(gpu_b, -1.0, d_minv_a_device);

      std::vector<double> solution_host;
      if (gpu_vp_amgx_solver) {
#ifdef ENABLE_AMGX
        GPU_STAGE2::AmgxCsrStats stats;
        GPU_STAGE2::solveDeviceCsrAmgx3D(
            gpu_vp_amgx_context, left_device, rhs_device, 0.0, &solution_host,
            &stats, &gpu_solved_p);
        ZIRAN_INFO("Splitting VP AMGX device CSR solver: rows=", stats.rows,
                   " nnz=", stats.nnz, " iterations=", stats.iterations,
                   " status=", stats.solve_status,
                   " rhs_upload_ms=", stats.rhs_upload_ms,
                   " setup_ms=", stats.setup_ms,
                   " solve_ms=", stats.solve_ms,
                   " solution_download_ms=", stats.solution_download_ms,
                   " total_ms=", stats.total_ms);
#else
        ZIRAN_ASSERT(false,
                     "-gpu_vp_amgx_solver requires ENABLE_AMGX");
#endif
      } else {
        // This is a useful A/B mode: sparse products are still built on
        // CUDA, while AMGCL_CUDA receives the identical compact CSR through
        // its established host compatibility interface.
        const GPU_STAGE3A::CsrMatrix left_host =
            GPU_STAGE3A::copyDeviceCsrToHost(left_device);
        const std::vector<double> rhs_host =
            GPU_STAGE3A::copyDeviceVectorToHost(rhs_device);
        TStack rhs = TStack::Zero(static_cast<int>(rhs_host.size()));
        for (int i = 0; i < rhs.rows(); ++i)
          rhs(i) = static_cast<T>(rhs_host[static_cast<std::size_t>(i)]);
        solved_p = DirectSolver<T>::solveCsrCUDA(
            left_host.rows, left_host.cols, left_host.row_offsets,
            left_host.col_indices, left_host.values, rhs, relative_tol,
            abs_tol, max_iter, -1, 1, 0, {});
        solution_host.resize(static_cast<std::size_t>(solved_p.rows()));
        for (int i = 0; i < solved_p.rows(); ++i)
          solution_host[static_cast<std::size_t>(i)] =
              static_cast<double>(solved_p(i));
        gpu_solved_p = GPU_STAGE3A::makeDeviceVectorFromHost(solution_host);
      }
      ZIRAN_ASSERT(solution_host.size() == static_cast<std::size_t>(num_p),
                   "GPU VP pressure solution size mismatch");
      solved_p = TStack::Zero(num_p);
      for (int i = 0; i < num_p; ++i)
        solved_p(i) = static_cast<T>(solution_host[static_cast<std::size_t>(i)]);
      gpu_solved_p_valid = true;
      constructVelocityFromSolvedP();
      return;
    }
    // Eigen::SparseMatrix<T> left = S - L;
    Eigen::SparseMatrix<T> left = S - D * M_inv * G;
    TStack right = b - D * M_inv * a;

    if (solverType == EIGEN)
      solved_p = DirectSolver<T>::solve(left, right, DirectSolver<T>::EIGEN);
    else if (solverType == AMGCL)
      solved_p = DirectSolver<T>::solve(left, right, DirectSolver<T>::AMGCL,
                                        relative_tol, abs_tol, max_iter, -1, 1,
                                        false, diag_scaling);
    else
      solved_p = DirectSolver<T>::solve(
          left, right, DirectSolver<T>::AMGCL_CUDA, relative_tol, abs_tol,
          max_iter, -1, 1, false, diag_scaling);

    gpu_solved_p_valid = false;
    constructVelocityFromSolvedP();
  }

  StdVector<TV> override_X;
  StdVector<TV> override_V;
  StdVector<TM> override_gradVp;
  StdVector<T> override_J;
  void constructVelocityFromSolvedP() {
    ZIRAN_TIMER();
    if (category == MATERIAL_PHASE_FLUID) {
      gpu_velocity_transfer_device = {};
      gpu_velocity_transfer_device_x_valid = false;
      gpu_velocity_transfer_device_v_grad_valid = false;
      // Do not mark host X/V valid here: a previous full-pipeline substep may
      // intentionally have left them stale while rebuilding from device state.
      gpu_velocity_transfer_host_grad_v_valid = false;
      gpu_velocity_transfer_host_pressure_valid = false;
    } else {
      gpu_solid_particle_g2p_ready = false;
    }
    GPU_STAGE3A::DeviceVector device_velocity;
    GPU_STAGE3A::DeviceVector device_pressure;
    bool fluid_velocity_transfer_ready = false;
    bool solid_device_transfer_ready = false;
    if (gpu_device_assembly_valid) {
      if (gpu_solved_p_valid &&
          gpu_solved_p.size == static_cast<std::size_t>(solved_p.rows())) {
        device_pressure = gpu_solved_p;
      } else {
        std::vector<double> pressure(static_cast<std::size_t>(solved_p.rows()));
        for (int i = 0; i < solved_p.rows(); ++i)
          pressure[static_cast<std::size_t>(i)] =
              static_cast<double>(solved_p(i));
        device_pressure = GPU_STAGE3A::makeDeviceVectorFromHost(pressure);
      }
      device_velocity = GPU_STAGE3A::computePressureVelocityDevice(
          gpu_velocity_algebra, gpu_m_inv, gpu_g, gpu_a, device_pressure);
      if constexpr (dim == 3) {
        if (category == MATERIAL_PHASE_SOLID && solid_Q2Q0 &&
            GPU_STAGE3A::persistentSolidParticleStateValid(
                gpu_solid_particle_state,
                static_cast<std::size_t>(particles.count)) &&
            gpu_velocity_node_map.size * dim == device_velocity.size &&
            gpu_pressure_node_map.size == device_pressure.size) {
          const bool owner_oracle =
              std::getenv("ZIRAN_GPU_SOLID_PARTICLE_OWNER_ORACLE") != nullptr;
          GPU_STAGE3A::SolidParticleStateStats owner_stats;
          GPU_STAGE3A::updatePersistentSolidParticlesQ2FromDevice3D(
              gpu_solid_particle_state, gpu_velocity_node_map,
              gpu_pressure_node_map, device_velocity, device_pressure,
              static_cast<double>(Base::dx), static_cast<double>(Base::dt),
              static_cast<double>(Base::apic_rpic_ratio),
              static_cast<double>(Base::D_inverse),
              owner_oracle ? &owner_stats : nullptr);
          if (owner_oracle) {
            ZIRAN_ASSERT(owner_stats.missing_velocity_nodes == 0 &&
                             owner_stats.missing_pressure_nodes == 0,
                         "GPU solid particle owner lookup failed");
            ZIRAN_INFO("GPU solid particle owner Q2 update: particles=",
                owner_stats.particles, " velocity_nodes=",
                owner_stats.velocity_nodes, " pressure_nodes=",
                owner_stats.pressure_nodes, " missing_velocity=",
                owner_stats.missing_velocity_nodes, " missing_pressure=",
                owner_stats.missing_pressure_nodes, " g2p_ms=",
                owner_stats.g2p_ms);
          }
          gpu_solid_particle_g2p_ready = true;
          solid_device_transfer_ready = gpu_solid_device_resident &&
              std::getenv("ZIRAN_GPU_SOLID_PARTICLE_OWNER_ORACLE") == nullptr &&
              std::getenv("ZIRAN_SOLID_VELOCITY_FIELD_DUMP_PREFIX") == nullptr &&
              std::getenv("ZIRAN_CONSTRUCT_VELOCITY_DEVICE_HOST_ORACLE") == nullptr;
        }
      }
      if constexpr (dim == 3) {
        if (category == MATERIAL_PHASE_SOLID &&
            std::getenv("ZIRAN_CONSTRUCT_VELOCITY_DEVICE_HOST_ORACLE")) {
          // Verify only the post-solve algebra used by
          // constructVelocityFromSolvedP: v = M^{-1}(a - Gp).  It uses the
          // exact device operands after interface-alpha application, so it
          // cannot conflate a wrong pressure solve with a wrong writeback.
          const GPU_STAGE3A::CsrMatrix host_m_inv =
              GPU_STAGE3A::copyDeviceCsrToHost(gpu_m_inv);
          const GPU_STAGE3A::CsrMatrix host_g =
              GPU_STAGE3A::copyDeviceCsrToHost(gpu_g);
          const std::vector<double> host_a =
              GPU_STAGE3A::copyDeviceVectorToHost(gpu_a);
          const std::vector<double> host_p =
              GPU_STAGE3A::copyDeviceVectorToHost(device_pressure);
          const std::vector<double> host_velocity =
              GPU_STAGE3A::copyDeviceVectorToHost(device_velocity);
          ZIRAN_ASSERT(host_g.rows == static_cast<int>(host_a.size()) &&
                           host_g.cols == static_cast<int>(host_p.size()) &&
                           host_m_inv.rows == static_cast<int>(host_velocity.size()) &&
                           host_m_inv.cols == host_g.rows,
                       "constructVelocity device/host oracle dimensions disagree");
          std::vector<double> rhs(host_a);
          for (int row = 0; row < host_g.rows; ++row) {
            double gradient = 0;
            for (int k = host_g.row_offsets[static_cast<std::size_t>(row)];
                 k < host_g.row_offsets[static_cast<std::size_t>(row + 1)]; ++k)
              gradient += host_g.values[static_cast<std::size_t>(k)] *
                  host_p[static_cast<std::size_t>(
                      host_g.col_indices[static_cast<std::size_t>(k)])];
            rhs[static_cast<std::size_t>(row)] -= gradient;
          }
          double max_abs = 0;
          double diff_l2 = 0;
          double reference_l2 = 0;
          for (int row = 0; row < host_m_inv.rows; ++row) {
            double expected = 0;
            for (int k = host_m_inv.row_offsets[static_cast<std::size_t>(row)];
                 k < host_m_inv.row_offsets[static_cast<std::size_t>(row + 1)]; ++k)
              expected += host_m_inv.values[static_cast<std::size_t>(k)] *
                  rhs[static_cast<std::size_t>(
                      host_m_inv.col_indices[static_cast<std::size_t>(k)])];
            const double difference = expected -
                host_velocity[static_cast<std::size_t>(row)];
            max_abs = std::max(max_abs, std::abs(difference));
            diff_l2 += difference * difference;
            reference_l2 += expected * expected;
          }
          ZIRAN_INFO("constructVelocity device/host oracle: rows=",
              host_m_inv.rows, " max_abs=", max_abs,
              " diff_l2=", std::sqrt(diff_l2),
              " relative_l2=", reference_l2 > 0
                  ? std::sqrt(diff_l2 / reference_l2) : std::sqrt(diff_l2));
        }
      }
      if constexpr (dim == 3) {
        if (category == MATERIAL_PHASE_FLUID) {
          if (const char* dump_prefix =
                  std::getenv("ZIRAN_FLUID_VELOCITY_FIELD_DUMP_PREFIX")) {
            // Cross-path diagnostic: materialize the post-pressure velocity
            // by physical grid key, not by either path's DOF number. This is
            // deliberately opt-in because it downloads the device vector.
            const std::vector<double> host_velocity =
                GPU_STAGE3A::copyDeviceVectorToHost(device_velocity);
            struct VelocityEntry {
              std::uint64_t key;
              double x, y, z;
            };
            std::vector<VelocityEntry> entries;
            if (gpu_prebuilt_velocity_valid) {
              entries.reserve(gpu_velocity_nodes.size());
              for (const auto& node : gpu_velocity_nodes) {
                const std::size_t offset =
                    static_cast<std::size_t>(node.idx * dim);
                entries.push_back({node.key, host_velocity[offset],
                    host_velocity[offset + 1], host_velocity[offset + 2]});
              }
            } else {
              entries.reserve(static_cast<std::size_t>(grid_comm.getNumNodes()));
              grid_comm.iterateGridSerial(
                  [&](IV node, GridState<T, dim>& g) {
                    const std::size_t offset =
                        static_cast<std::size_t>(g.idx * dim);
                    entries.push_back({GPU_STAGE3A::packGridKey3D(
                        node[0], node[1], node[2]), host_velocity[offset],
                        host_velocity[offset + 1], host_velocity[offset + 2]});
                  });
            }
            std::sort(entries.begin(), entries.end(),
                      [](const VelocityEntry& a, const VelocityEntry& b) {
                        return a.key < b.key;
                      });
            static int dump_index = 0;
            const std::string path = std::string(dump_prefix) + "_" +
                std::to_string(dump_index++) + ".bin";
            std::ofstream out(path, std::ios::binary | std::ios::trunc);
            const std::uint64_t count = entries.size();
            out.write(reinterpret_cast<const char*>(&count), sizeof(count));
            for (const auto& entry : entries) {
              out.write(reinterpret_cast<const char*>(&entry.key),
                        sizeof(entry.key));
              out.write(reinterpret_cast<const char*>(&entry.x), sizeof(entry.x));
              out.write(reinterpret_cast<const char*>(&entry.y), sizeof(entry.y));
              out.write(reinterpret_cast<const char*>(&entry.z), sizeof(entry.z));
            }
            ZIRAN_ASSERT(out.good(), "failed to write fluid velocity-field dump");
            ZIRAN_INFO("Fluid velocity-field dump: ", path,
                       " nodes=", entries.size());
          }
        }
      }
      // The first GPU G2P version still downloads X/V/gradV for CPU state
      // writeback. It is therefore an opt-in A/B path until the particle
      // state mirror is device-resident; normal production inputs retain the
      // faster CPU gather rather than silently regressing.
      const bool enable_gpu_fluid_velocity_transfer =
          gpu_fluid_velocity_transfer ||
          std::getenv("ZIRAN_ENABLE_GPU_FLUID_VELOCITY_TRANSFER") != nullptr;
      fluid_velocity_transfer_ready = category == MATERIAL_PHASE_FLUID &&
          fluid_Q1Q0 && gpu_prebuilt_velocity_valid &&
          enable_gpu_fluid_velocity_transfer;
      if (!fluid_velocity_transfer_ready && !solid_device_transfer_ready) {
        const std::vector<double> velocity =
            GPU_STAGE3A::copyDeviceVectorToHost(device_velocity);
        solved_v = TStack::Zero(static_cast<int>(velocity.size()));
        for (int i = 0; i < solved_v.rows(); ++i)
          solved_v(i) = static_cast<T>(velocity[static_cast<std::size_t>(i)]);
      }
    } else {
      solved_v = M_inv * a - M_inv * G * solved_p;
    }

    if (category == MATERIAL_PHASE_SOLID && solid_device_transfer_ready) {
      ZIRAN_INFO("Solid post-pressure velocity/G2P remains device-resident: "
                 "velocity_rows=", device_velocity.size,
                 " pressure_rows=", device_pressure.size);
      return;
    }

    if (category == MATERIAL_PHASE_SOLID) {
      if constexpr (dim == 3) {
        if (const char* dump_prefix =
                std::getenv("ZIRAN_SOLID_VELOCITY_FIELD_DUMP_PREFIX")) {
          // Compare the physical solid velocity field across CPU/GPU paths.
          // The ordered linear vector alone is not a valid oracle once either
          // path is allowed to choose its own sparse-grid/DOF ordering.
          struct VelocityEntry {
            std::uint64_t key;
            double x, y, z;
          };
          std::vector<VelocityEntry> entries;
          entries.reserve(static_cast<std::size_t>(grid.getNumNodes()));
          grid.iterateGridSerial([&](IV node, GridState<T, dim>& g) {
            const std::size_t offset = static_cast<std::size_t>(g.idx * dim);
            entries.push_back({GPU_STAGE3A::packGridKey3D(
                node[0], node[1], node[2]),
                static_cast<double>(solved_v(offset)),
                static_cast<double>(solved_v(offset + 1)),
                static_cast<double>(solved_v(offset + 2))});
          });
          std::sort(entries.begin(), entries.end(),
                    [](const VelocityEntry& a, const VelocityEntry& b) {
                      return a.key < b.key;
                    });
          static int dump_index = 0;
          const std::string path = std::string(dump_prefix) + "_" +
              std::to_string(dump_index++) + ".bin";
          std::ofstream out(path, std::ios::binary | std::ios::trunc);
          const std::uint64_t count = entries.size();
          out.write(reinterpret_cast<const char*>(&count), sizeof(count));
          for (const auto& entry : entries) {
            out.write(reinterpret_cast<const char*>(&entry.key),
                      sizeof(entry.key));
            out.write(reinterpret_cast<const char*>(&entry.x), sizeof(entry.x));
            out.write(reinterpret_cast<const char*>(&entry.y), sizeof(entry.y));
            out.write(reinterpret_cast<const char*>(&entry.z), sizeof(entry.z));
          }
          ZIRAN_ASSERT(out.good(),
                       "failed to write solid velocity-field diagnostic dump");
          ZIRAN_INFO("Solid velocity-field dump: ", path,
                     " nodes=", entries.size());
        }
      }
      ZIRAN_ASSERT(grid.getNumNodes() * dim == solved_v.rows(),
                   "dimension not match");
      grid.iterateGridSerial([&](IV node, GridState<T, dim> &g) {
        for (int d = 0; d < dim; ++d)
          g.new_v[d] = solved_v(g.idx * dim + d);
      });
      if (solid_Q2Q0) {
        if (gpu_prebuilt_solid_pressure_valid) {
          override_J.resize(particles.count);
          auto *j_model = particles.DataManager::getPointer(
              MaterialForce::j_constitutive_model_name());
          for (int i = 0; i < particles.count; ++i) {
            const TV shifted =
                particles.X.array[i] - TV::Ones() * Base::dx * (T)0.5;
            IV node;
            for (int d = 0; d < dim; ++d)
              node[d] = static_cast<int>(std::floor(shifted[d] / Base::dx));
            const auto key = GPU_STAGE3A::packGridKey3D(
                node[0], node[1], node[2]);
            auto it = std::lower_bound(
                gpu_pressure_nodes.begin(), gpu_pressure_nodes.end(), key,
                [](const GPU_STAGE3A::AssemblyGridNode &entry,
                   GPU_STAGE3A::GridKey value) { return entry.key < value; });
            ZIRAN_ASSERT(it != gpu_pressure_nodes.end() && it->key == key,
                         "GPU solid pressure DOF not found");
            const T p = solved_p(it->idx);
            override_J[i] = -p / (*j_model)[i].lambda + 1;
          }
        } else {
        StdVector<TV> &X_for_p = particles.X.array;
        MpmGrid<T, dim, 0> grid4;
        // grid4.activatePages(particles.X.array, Base::dx, 0, 1, -TV::Ones() *
        // Base::dx * 0.5);
        grid4.activatePages(X_for_p, Base::dx, 0, 1, -TV::Ones() * Base::dx * 0.5);
        // grid4.activatePages(particles.X.array, Base::dx, 0, 1);
        for (auto Xp : X_for_p) {
          // BSplineWeights<T, dim, 0> spline(Xp, Base::dx);
          BSplineWeights<T, dim, 0> spline(Xp - TV::Ones() * Base::dx * 0.5,
                                           Base::dx);
          uint64_t offset =
              Base::SparseMask::Linear_Offset(to_std_array(spline.base_node));
          grid4.iterateKernel(spline, offset,
                              [&](const IV &node, T w, const TV &dw,
                                  GridState<T, dim> &g) { g.m += w; });
        }
        int num4 = grid4.getNumNodes();
        ZIRAN_ASSERT(num4 == solved_p.rows(), "This is crazy.");
        override_J.resize(particles.count);
        auto *j_model = particles.DataManager::getPointer(
            MaterialForce::j_constitutive_model_name());
        for (int i = 0; i < particles.count; ++i) {
          TV Xp = X_for_p[i];
          // BSplineWeights<T, dim, 1> spline(Xp, Base::dx);
          BSplineWeights<T, dim, 0> spline(Xp - TV::Ones() * Base::dx * 0.5,
                                           Base::dx);
          // BSplineWeights<T, dim, 1> spline(Xp - TV::Ones() * Base::dx * 0.5,
          // Base::dx);
          ZIRAN_ASSERT(grid4[spline.base_node].idx >= 0, "This is crazy.");
          // 看起来G2P得到粒子压强的结果有点奇怪
          // T p = 0.0;
          // uint64_t offset =
          // Base::SparseMask::Linear_Offset(to_std_array(spline.base_node));
          // grid4.iterateKernel(spline, offset,
          //                   [&](IV node, T w, TV dw, GridState<T, dim> &g4) {
          //                     p += w * solved_p(g4.idx);
          //                   });
          // grid4.iterateGrid([&](IV node, GridState<T, dim>& g) {
          //   p /= g.m;
          // });

          T p = solved_p(grid4[spline.base_node].idx);
          // if(p!=0.0)printf("%f\n",p);
          override_J[i] = -p / (*j_model)[i].lambda + 1;
        }
        }
      }
    } else {
      if (fluid_Q1Q0) {
        if (gpu_prebuilt_velocity_valid) {
          override_X.resize(particles.count);
          override_V.resize(particles.count);
          override_gradVp.resize(particles.count);
          if constexpr (dim == 3) {
            if (fluid_velocity_transfer_ready) {
              static_assert(sizeof(TV) == sizeof(GPU_STAGE2::Vec3d),
                  "GPU velocity transfer requires tightly packed 3D particle positions");
              std::vector<GPU_STAGE2::GridKey> keys;
              std::vector<int> indices;
              std::vector<GPU_STAGE2::GridKey> g2p_fallback_keys;
              std::vector<GPU_STAGE2::Vec3d> g2p_fallback_velocity;
              std::vector<GPU_STAGE2::GridKey> pressure_keys;
              std::vector<int> pressure_indices;
              {
                ZIRAN_NAMED_TIMER("gpuFluidVelocityNodePack");
                keys.reserve(gpu_velocity_nodes.size());
                indices.reserve(gpu_velocity_nodes.size());
                g2p_fallback_keys.reserve(
                    gpu_velocity_g2p_fallback_nodes.size());
                g2p_fallback_velocity.reserve(
                    gpu_velocity_g2p_fallback_nodes.size());
                pressure_keys.reserve(device_pressure.size);
                pressure_indices.reserve(device_pressure.size);
                for (const auto& node : gpu_velocity_nodes) {
                  keys.push_back(node.key);
                  indices.push_back(node.idx);
                }
                for (const auto& node : gpu_velocity_g2p_fallback_nodes) {
                  g2p_fallback_keys.push_back(node.key);
                  g2p_fallback_velocity.push_back(GPU_STAGE2::Vec3d{
                      node.new_v.x, node.new_v.y, node.new_v.z});
                }
                for (const auto& node : gpu_pressure_nodes) {
                  // The compatibility grid retains initial-only nodes with
                  // idx=-1. They are not pressure DOFs and the old CPU
                  // lookup deliberately ignored them as well.
                  if (node.idx >= 0 && static_cast<std::size_t>(node.idx) <
                          device_pressure.size) {
                    pressure_keys.push_back(node.key);
                    pressure_indices.push_back(node.idx);
                  }
                }
              }
              GPU_STAGE2::VelocityTransferHostView transfer;
              GPU_STAGE2::VelocityTransferStats transfer_stats;
              const bool velocity_transfer_oracle =
                  std::getenv("ZIRAN_GPU_FLUID_VELOCITY_COMPARE") != nullptr;
              GPU_STAGE2::VelocityTransferDownloadMask transfer_download;
              const char* staggered_snap_env =
                  std::getenv("ZIRAN_GPU_FLUID_STAGGERED_SNAP_EPS");
              const bool staggered_snap_enabled = staggered_snap_env &&
                  std::strtod(staggered_snap_env, nullptr) > 0.0;
              const bool device_resident_particle_output =
                  gpu_fluid_device_resident && !velocity_transfer_oracle &&
                  !staggered_snap_enabled &&
                  (gpu_box_shell_collision.valid ||
                   Base::collision_objects.empty());
              transfer_download.x = !device_resident_particle_output;
              transfer_download.v = !device_resident_particle_output;
              // Full-pipeline mode keeps X/V/gradV device-resident. The
              // compatibility path still downloads X/V; gradV is synchronized
              // only at an explicit restart/output boundary or by an oracle.
              transfer_download.grad_v = velocity_transfer_oracle;
              // Particle pressure is visualization/restart state. Keep it on
              // device across substeps and synchronize it only at an explicit
              // host-output boundary (or for the full CPU oracle).
              transfer_download.pressure = velocity_transfer_oracle;
              {
                ZIRAN_NAMED_TIMER("gpuFluidVelocityTransfer");
                GPU_STAGE2::transferFluidVelocityQ1FromDevice3D(
                    gpu_velocity_transfer, &gpu_fluid_analytic,
                    &gpu_velocity_node_map, &gpu_pressure_node_map,
                    particles.X.array.data(),
                    static_cast<std::size_t>(particles.count), keys, indices,
                    g2p_fallback_keys, g2p_fallback_velocity,
                    device_velocity, pressure_keys, pressure_indices,
                    device_pressure, static_cast<double>(Base::dx),
                    static_cast<double>(Base::dt), transfer,
                    gpu_velocity_transfer_device, &transfer_stats,
                    transfer_download);
              }
              gpu_velocity_transfer_device_x_valid =
                  gpu_velocity_transfer_device.x != nullptr &&
                  gpu_velocity_transfer_device.size ==
                      static_cast<std::size_t>(particles.count);
              gpu_velocity_transfer_device_v_grad_valid =
                  gpu_velocity_transfer_device.v != nullptr &&
                  gpu_velocity_transfer_device.grad_v != nullptr &&
                  gpu_velocity_transfer_device.size ==
                      static_cast<std::size_t>(particles.count);
              gpu_velocity_transfer_host_x_valid = transfer.x != nullptr;
              gpu_velocity_transfer_host_v_valid = transfer.v != nullptr;
              gpu_velocity_transfer_host_grad_v_valid =
                  transfer.grad_v != nullptr;
              gpu_velocity_transfer_host_pressure_valid =
                  transfer.pressure != nullptr;
              if (velocity_transfer_oracle) {
                // Debug-only oracle for the device Q1 gather. Keep this out
                // of the production path: it intentionally downloads the
                // velocity and recomputes the old CPU interpolation.
                const std::vector<double> reference_velocity =
                    GPU_STAGE3A::copyDeviceVectorToHost(device_velocity);
                double max_x = 0.0, max_v = 0.0, max_grad = 0.0;
                double max_pressure = 0.0;
                for (int p = 0; p < particles.count; ++p) {
                  const TV Xp = particles.X.array[p];
                  const TV shifted = Xp - TV::Ones() * Base::dx * (T)0.5;
                  IV base;
                  T w[3][2];
                  for (int d = 0; d < dim; ++d) {
                    const T gx = shifted[d] / Base::dx;
                    base[d] = static_cast<int>(std::floor(gx));
                    w[d][1] = gx - (T)base[d];
                    w[d][0] = (T)1 - w[d][1];
                  }
                  TV pic = TV::Zero();
                  TM grad = TM::Zero();
                  for (int i = 0; i < 2; ++i)
                    for (int j = 0; j < 2; ++j)
                      for (int k = 0; k < 2; ++k) {
                        IV node = base;
                        node[0] += i;
                        node[1] += j;
                        node[2] += k;
                        const auto key = GPU_STAGE3A::packGridKey3D(
                            node[0], node[1], node[2]);
                        const auto it = std::lower_bound(
                            gpu_velocity_nodes.begin(), gpu_velocity_nodes.end(), key,
                            [](const GPU_STAGE3A::AssemblyGridNode& entry,
                               GPU_STAGE3A::GridKey value) { return entry.key < value; });
                        TV node_v;
                        if (it != gpu_velocity_nodes.end() && it->key == key) {
                          for (int d = 0; d < dim; ++d)
                            node_v[d] = static_cast<T>(reference_velocity[
                                static_cast<std::size_t>(it->idx * dim + d)]);
                        } else {
                          const auto fallback = std::lower_bound(
                              gpu_velocity_g2p_fallback_nodes.begin(),
                              gpu_velocity_g2p_fallback_nodes.end(), key,
                              [](const GPU_STAGE3A::AssemblyGridNode& entry,
                                 GPU_STAGE3A::GridKey value) {
                                return entry.key < value;
                              });
                          if (fallback == gpu_velocity_g2p_fallback_nodes.end() ||
                              fallback->key != key)
                            continue;
                          node_v = TV(static_cast<T>(fallback->new_v.x),
                                      static_cast<T>(fallback->new_v.y),
                                      static_cast<T>(fallback->new_v.z));
                        }
                        pic += (w[0][i] * w[1][j] * w[2][k]) * node_v;
                        const T derivatives[3] = {
                            ((i == 0) ? (T)-1 : (T)1) / Base::dx * w[1][j] * w[2][k],
                            w[0][i] * ((j == 0) ? (T)-1 : (T)1) / Base::dx * w[2][k],
                            w[0][i] * w[1][j] * ((k == 0) ? (T)-1 : (T)1) / Base::dx};
                        for (int d = 0; d < dim; ++d)
                          grad.col(d) += node_v * derivatives[d];
                      }
                  const auto& gpu_x = transfer.x[static_cast<std::size_t>(p)];
                  const auto& gpu_v = transfer.v[static_cast<std::size_t>(p)];
                  const auto& gpu_grad = transfer.grad_v[static_cast<std::size_t>(p)];
                  double reference_pressure = 0.0;
                  const auto pressure_key = GPU_STAGE3A::packGridKey3D(
                      base[0], base[1], base[2]);
                  const auto pressure_it = std::lower_bound(
                      gpu_pressure_nodes.begin(), gpu_pressure_nodes.end(),
                      pressure_key,
                      [](const GPU_STAGE3A::AssemblyGridNode& entry,
                         GPU_STAGE3A::GridKey value) {
                        return entry.key < value;
                      });
                  if (pressure_it != gpu_pressure_nodes.end() &&
                      pressure_it->key == pressure_key && pressure_it->idx >= 0 &&
                      pressure_it->idx < solved_p.rows())
                    reference_pressure = static_cast<double>(
                        solved_p(pressure_it->idx));
                  max_pressure = std::max(max_pressure, std::abs(
                      reference_pressure - transfer.pressure[
                          static_cast<std::size_t>(p)]));
                  const TV cpu_x = Xp + pic * Base::dt;
                  for (int d = 0; d < dim; ++d) {
                    max_x = std::max(max_x, std::abs(static_cast<double>(cpu_x[d]) -
                        (d == 0 ? gpu_x.x : (d == 1 ? gpu_x.y : gpu_x.z))));
                    max_v = std::max(max_v, std::abs(static_cast<double>(pic[d]) -
                        (d == 0 ? gpu_v.x : (d == 1 ? gpu_v.y : gpu_v.z))));
                    for (int r = 0; r < dim; ++r)
                      max_grad = std::max(max_grad, std::abs(static_cast<double>(grad(r, d)) -
                          gpu_grad.values[r + 3 * d]));
                  }
                }
                ZIRAN_INFO("GPU fluid velocity transfer oracle: max_x=", max_x,
                    " max_v=", max_v, " max_grad=", max_grad,
                    " max_pressure=", max_pressure);
              }
              {
                // The device transfer deliberately returns pinned host views
                // because gridToParticles remains CPU-owned.  This was
                // accidentally copied into the authoritative arrays on one
                // CPU thread, even though particles are independent.
                ZIRAN_NAMED_TIMER("gpuFluidVelocityWriteback");
                if (transfer.pressure)
                  override_J.resize(particles.count);
                tbb::parallel_for(0, particles.count, [&](int p) {
                  if (transfer.x) {
                    const auto& x = transfer.x[static_cast<std::size_t>(p)];
                    override_X[p] = TV(static_cast<T>(x.x), static_cast<T>(x.y),
                                       static_cast<T>(x.z));
                  }
                  if (transfer.v) {
                    const auto& v = transfer.v[static_cast<std::size_t>(p)];
                    override_V[p] = TV(static_cast<T>(v.x), static_cast<T>(v.y),
                                       static_cast<T>(v.z));
                  }
                  if (transfer.grad_v) {
                    const auto& grad =
                        transfer.grad_v[static_cast<std::size_t>(p)];
                    for (int col = 0; col < 3; ++col)
                      for (int row = 0; row < 3; ++row)
                        override_gradVp[p](row, col) =
                            static_cast<T>(grad.values[row + 3 * col]);
                  }
                  if (transfer.pressure)
                    override_J[p] = static_cast<T>(
                        transfer.pressure[static_cast<std::size_t>(p)]);
                });
              }
              ZIRAN_INFO("GPU fluid velocity transfer: particles=", transfer_stats.particles,
                  " nodes=", transfer_stats.velocity_nodes,
                  " g2p_fallback_nodes=", transfer_stats.g2p_fallback_nodes,
                  " resident_particles=",
                  transfer_stats.resident_particle_input ? 1 : 0,
                  " resident_nodes=",
                  transfer_stats.resident_node_input ? 1 : 0,
                  " resident_fallback=",
                  transfer_stats.resident_fallback_input ? 1 : 0,
                  " host_download_bytes=",
                  transfer_stats.host_download_bytes,
                  " upload_particles_ms=", transfer_stats.particle_upload_ms,
                  " upload_nodes_ms=", transfer_stats.node_upload_ms,
                  " g2p_ms=", transfer_stats.g2p_ms,
                  " download_ms=", transfer_stats.download_ms,
                  " total_ms=", transfer_stats.total_ms);
            }
          }
          if (!fluid_velocity_transfer_ready) tbb::parallel_for(0, (int)particles.count, [&](int p) {
            const TV Xp = particles.X.array[p];
            const TV shifted = Xp - TV::Ones() * Base::dx * (T)0.5;
            IV base;
            T w[3][2];
            for (int d = 0; d < dim; ++d) {
              const T gx = shifted[d] / Base::dx;
              base[d] = static_cast<int>(std::floor(gx));
              w[d][1] = gx - (T)base[d];
              w[d][0] = (T)1 - w[d][1];
            }
            TV picV = TV::Zero();
            TM gradVp = TM::Zero();
            for (int i = 0; i < 2; ++i)
              for (int j = 0; j < 2; ++j)
                for (int k = 0; k < 2; ++k) {
                  const int offsets[3] = {i, j, k};
                  IV node = base;
                  for (int d = 0; d < dim; ++d)
                    node[d] += offsets[d];
                  const auto key = GPU_STAGE3A::packGridKey3D(
                      node[0], node[1], node[2]);
                  auto it = std::lower_bound(
                      gpu_velocity_nodes.begin(), gpu_velocity_nodes.end(), key,
                      [](const GPU_STAGE3A::AssemblyGridNode &entry,
                         GPU_STAGE3A::GridKey value) {
                        return entry.key < value;
                      });
                  TV node_v;
                  if (it != gpu_velocity_nodes.end() && it->key == key) {
                    for (int d = 0; d < dim; ++d)
                      node_v[d] = solved_v(it->idx * dim + d);
                  } else {
                    const auto fallback = std::lower_bound(
                        gpu_velocity_g2p_fallback_nodes.begin(),
                        gpu_velocity_g2p_fallback_nodes.end(), key,
                        [](const GPU_STAGE3A::AssemblyGridNode& entry,
                           GPU_STAGE3A::GridKey value) {
                          return entry.key < value;
                        });
                    if (fallback == gpu_velocity_g2p_fallback_nodes.end() ||
                        fallback->key != key)
                      continue;
                    node_v = TV(static_cast<T>(fallback->new_v.x),
                                static_cast<T>(fallback->new_v.y),
                                static_cast<T>(fallback->new_v.z));
                  }
                  const T weight = w[0][i] * w[1][j] * w[2][k];
                  picV += weight * node_v;
                  const T grad[3] = {
                      ((i == 0) ? (T)-1 : (T)1) / Base::dx * w[1][j] * w[2][k],
                      w[0][i] * ((j == 0) ? (T)-1 : (T)1) / Base::dx * w[2][k],
                      w[0][i] * w[1][j] * ((k == 0) ? (T)-1 : (T)1) / Base::dx};
                  for (int d = 0; d < dim; ++d)
                    gradVp.col(d) += node_v * grad[d];
                }
            override_X[p] = Xp + picV * Base::dt;
            override_V[p] = picV;
            override_gradVp[p] = gradVp;
          });
          vis_interface_vel.assign(interface_GQ.size(), TV::Zero());
        } else {
        // MpmGrid<T, dim, 1> grid3;
        MpmGrid<T, dim, 1> &grid3 = grid_comm;
        grid3.iterateGridSerial([&](IV node, GridState<T, dim> &g) {
          for (int d = 0; d < dim; ++d)
            g.new_v[d] = solved_v(g.idx * dim + d);
        });
        override_X.resize(particles.count);
        override_V.resize(particles.count);
        override_gradVp.resize(particles.count);
        tbb::parallel_for(0, (int)particles.count, [&](int i) {
          TV Xp = particles.X.array[i];
          TV picV = TV::Zero();
          TM gradVp = TM::Zero();
          BSplineWeights<T, dim, 1> spline(Xp - TV::Ones() * Base::dx * 0.5,
                                           Base::dx);
          uint64_t offset =
              Base::SparseMask::Linear_Offset(to_std_array(spline.base_node));
          grid3.iterateKernel(spline, offset,
                              [&](IV node, T w, TV dw, GridState<T, dim> &g) {
                                picV += w * g.new_v;
                                gradVp.noalias() += g.new_v * dw.transpose();
                              });
          override_X[i] = Xp + picV * Base::dt;
          override_V[i] = picV;
          override_gradVp[i] = gradVp;
        });
        if (std::getenv("ZIRAN_FLUID_G2P_INACTIVE_NODE_PROBE")) {
          constexpr int tracked_particle = 84897;
          if (tracked_particle < particles.count) {
            const TV Xp = particles.X.array[tracked_particle];
            TV active_velocity = TV::Zero();
            TV inactive_velocity = TV::Zero();
            int active_nodes = 0;
            int inactive_nodes = 0;
            BSplineWeights<T, dim, 1> spline(
                Xp - TV::Ones() * Base::dx * (T)0.5, Base::dx);
            const uint64_t offset = Base::SparseMask::Linear_Offset(
                to_std_array(spline.base_node));
            grid3.iterateKernel(
                spline, offset, [&](IV, T w, TV, GridState<T, dim>& g) {
                  if (g.idx >= 0) {
                    active_velocity += w * g.new_v;
                    ++active_nodes;
                  } else {
                    inactive_velocity += w * g.new_v;
                    ++inactive_nodes;
                  }
                });
            ZIRAN_INFO("CPU G2P inactive-node probe: particle=",
                tracked_particle, " active_nodes=", active_nodes,
                " inactive_nodes=", inactive_nodes,
                " active_v=", active_velocity.transpose(),
                " inactive_v=", inactive_velocity.transpose(),
                " total_v=", override_V[tracked_particle].transpose());
          }
        }
        // 将g2p后interface上的速度打印到粒子上
        vis_interface_vel.resize(interface_GQ.size());
        tbb::parallel_for(0, (int)interface_GQ.size(), [&](int i) {
          TV Xp = interface_GQ[i];
          TV normal = interface_N[i];
          TV picV = TV::Zero();
          BSplineWeights<T, dim, 1> spline(Xp - TV::Ones() * Base::dx * 0.5,
                                           Base::dx);
          uint64_t offset =
              Base::SparseMask::Linear_Offset(to_std_array(spline.base_node));
          grid3.iterateKernel(spline, offset,
                              [&](IV node, T w, TV dw, GridState<T, dim> &g) {
                                picV += w * g.new_v;
                              });
          vis_interface_vel[i] = (picV.transpose() * normal) * normal;
          // 只是为了可视化的位置一样. interface_GQ 这时已经不需要了,拿来存一下.
          // interface_GQ[i] = Xp + picV * Base::dt;
        });
        }

        // 将压强储存在粒子上便于可视化
        // TODO:放到可视化模块
        if (gpu_prebuilt_fluid_dofs_valid) {
          if (!fluid_velocity_transfer_ready)
            override_J.resize(particles.count);
          // This is a visualization/compatibility pressure lookup, but its
          // former serial 630k-particle binary-search loop dominated the
          // outer constructVelocityFromSolvedP timer after Q1 G2P moved to
          // CUDA.  Each result is independent and retains the exact same
          // sorted-key lookup and missing-key behavior.
          if (!fluid_velocity_transfer_ready) {
            ZIRAN_NAMED_TIMER("gpuFluidPressureOverride");
            tbb::parallel_for(0, particles.count, [&](int i) {
            const TV shifted =
                particles.X.array[i] - TV::Ones() * Base::dx * (T)0.5;
            IV node;
            for (int d = 0; d < dim; ++d)
              node[d] = static_cast<int>(std::floor(shifted[d] / Base::dx));
            const auto key = GPU_STAGE3A::packGridKey3D(
                node[0], node[1], node[2]);
            const auto it = std::lower_bound(
                gpu_pressure_nodes.begin(), gpu_pressure_nodes.end(), key,
                [](const GPU_STAGE3A::AssemblyGridNode &entry,
                   GPU_STAGE3A::GridKey value) { return entry.key < value; });
            if (it != gpu_pressure_nodes.end() && it->key == key &&
                it->idx >= 0 && it->idx < solved_p.rows())
              override_J[i] = solved_p(it->idx);
            });
          }
        } else {
        MpmGrid<T, dim, 0> grid4;
        grid4.activatePages(quadrature_state.volume_GQ, Base::dx, 0, 1,
                      -TV::Ones() * Base::dx * 0.5);
        for (auto &Xp : quadrature_state.volume_GQ) {
          BSplineWeights<T, dim, 0> spline4(Xp - TV::Ones() * Base::dx * 0.5,
                                            Base::dx);
          uint64_t offset4 =
              Base::SparseMask::Linear_Offset(to_std_array(spline4.base_node));
          grid4.iterateKernel(spline4, offset4,
                              [&](const IV &node4, T w4, const TV &dw4,
                                  GridState<T, dim> &g4) { g4.m += w4; });
        }
        StdVector<TV> &X_for_p = particles.X.array;
        int num4 = grid4.getNumNodes();
        // solved_p这一段还含有边界,应该比num4大,所以先注释掉
        // ZIRAN_ASSERT(num4 == solved_p.rows(), "This is crazy.");
        override_J.resize(particles.count);
        auto *j_model = particles.DataManager::getPointer(
            MaterialForce::j_constitutive_model_name());
        for (int i = 0; i < particles.count; ++i) {
          TV Xp = X_for_p[i];
          // BSplineWeights<T, dim, 1> spline(Xp, Base::dx);
          BSplineWeights<T, dim, 0> spline(Xp - TV::Ones() * Base::dx * 0.5,
                                           Base::dx);
          // ZIRAN_ASSERT(grid4[spline.base_node].idx >= 0, "This is crazy.");
          if (grid4[spline.base_node].idx >= 0) {
            T p = solved_p(grid4[spline.base_node].idx);
            override_J[i] = p;
          }
        }
        }

      } else {
        MpmGrid<T, dim> grid3;
        grid3.activatePages(quadrature_state.volume_GQ, Base::dx);
        for (int i = 0; i < (int)quadrature_state.volume_GQ.size(); ++i) {
          TV &Xp = quadrature_state.volume_GQ[i];
          BSplineWeights<T, dim> spline(Xp, Base::dx);
          uint64_t offset =
              MpmSimulationBase<T, dim>::SparseMask::Linear_Offset(
                  to_std_array(spline.base_node));
          grid3.iterateKernel(spline, offset,
                              [&](const IV &node, T w, const TV &dw,
                                  GridState<T, dim> &g) { g.m += w; });
        }
        ZIRAN_ASSERT(grid3.getNumNodes() * dim == solved_v.rows(),
                     "dimension not match");
        grid3.iterateGridSerial([&](IV node, GridState<T, dim> &g) {
          for (int d = 0; d < dim; ++d)
            grid[node].new_v[d] = solved_v(g.idx * dim + d);
        });
      }
    }
  }

  bool reduceResidentFluidParticleState(
      double domain_min, double domain_max,
      GPU_STAGE2::FluidParticleStateStats& stats) const {
#ifdef ENABLE_CUDA_STAGE2_PROBE
    if constexpr (dim == 3) {
      if (category == MATERIAL_PHASE_FLUID && gpu_fluid_device_resident &&
          gpu_velocity_transfer_device_x_valid &&
          gpu_velocity_transfer_device_v_grad_valid &&
          gpu_velocity_transfer_device.x != nullptr &&
          gpu_velocity_transfer_device.v != nullptr &&
          gpu_velocity_transfer_device.size ==
              static_cast<std::size_t>(particles.count)) {
        GPU_STAGE2::reduceFluidParticleState3D(
            gpu_velocity_transfer_device, domain_min, domain_max, stats);
        return true;
      }
    }
#endif
    return false;
  }

  bool reduceResidentSolidParticleState(
      GPU_STAGE3A::SolidParticleReductionStats& stats) const {
#ifdef ENABLE_CUDA_STAGE2_PROBE
    if constexpr (dim == 3) {
      if (category == MATERIAL_PHASE_SOLID && gpu_solid_device_resident &&
          GPU_STAGE3A::persistentSolidParticleStateValid(
              gpu_solid_particle_state,
              static_cast<std::size_t>(particles.count))) {
        GPU_STAGE3A::reducePersistentSolidParticleState3D(
            gpu_solid_particle_state, stats);
        return true;
      }
    }
#endif
    return false;
  }

  void sortParticlesAndActivateGrid() override {
#ifdef ENABLE_CUDA_STAGE2_PROBE
    if constexpr (dim == 3) {
      const bool resident_fluid_grid_bypass =
          category == MATERIAL_PHASE_FLUID && gpu_fluid_device_resident &&
          gpu_velocity_transfer_device_x_valid &&
          gpu_velocity_transfer_device_v_grad_valid &&
          gpu_velocity_transfer_device.x != nullptr &&
          gpu_velocity_transfer_device.v != nullptr &&
          gpu_velocity_transfer_device.size ==
              static_cast<std::size_t>(particles.count) &&
          gpu_build_system && !gpu_build_system_cpu_numerical_grid &&
          !gpu_build_system_cpu_pressure_grid &&
          !gpu_build_system_cpu_velocity_grid;
      const bool resident_solid_grid_bypass =
          category == MATERIAL_PHASE_SOLID && gpu_solid_device_resident &&
          GPU_STAGE3A::persistentSolidParticleStateValid(
              gpu_solid_particle_state,
              static_cast<std::size_t>(particles.count)) &&
          canUseResidentSolidDeviceGrid();
      if (resident_fluid_grid_bypass) {
        // The coupling full-pipeline rebuilds every fluid sparse field from
        // the current device owner and bypasses legacy fluid P2G/G2P. Avoid
        // sorting deliberately stale host X and activating an SPGrid that no
        // production consumer reads. The first substep and every invalidated
        // or compatibility path still use the Base implementation.
        ZIRAN_INFO("Bypassing legacy fluid particle sort/grid pollute: "
                   "resident Q1 path=1");
        return;
      }
      if (resident_solid_grid_bypass) {
        ZIRAN_INFO("Bypassing legacy solid particle sort/grid pollute: "
                   "resident Q2 path=1");
        return;
      }
    }
#endif
    Base::sortParticlesAndActivateGrid();
  }

  double calculateDt() override {
#ifdef ENABLE_CUDA_STAGE2_PROBE
    if constexpr (dim == 3) {
      GPU_STAGE2::FluidParticleStateStats stats;
      if (reduceResidentFluidParticleState(
              -std::numeric_limits<double>::infinity(),
              std::numeric_limits<double>::infinity(), stats)) {
        TV p_min_corner(static_cast<T>(stats.min_corner.x),
                        static_cast<T>(stats.min_corner.y),
                        static_cast<T>(stats.min_corner.z));
        TV p_max_corner(static_cast<T>(stats.max_corner.x),
                        static_cast<T>(stats.max_corner.y),
                        static_cast<T>(stats.max_corner.z));
        ZIRAN_INFO("Particle Min Corner: ", p_min_corner.transpose());
        ZIRAN_INFO("Particle Max Corner: ", p_max_corner.transpose());
        p_min_corner.array() -= (Base::interpolation_degree + 2) * Base::dx;
        p_max_corner.array() += (Base::interpolation_degree + 2) * Base::dx;
        ZIRAN_INFO("Maximum particle speed: ", stats.max_speed);
        const T max_collision_object_speed = 0;
        ZIRAN_INFO("Maximum collision object speed: ",
                   max_collision_object_speed);
        const double max_speed = std::max(
            stats.max_speed, static_cast<double>(max_collision_object_speed));
        double dt_compute = Base::step.max_dt;
        if (max_speed)
          dt_compute = Base::cfl * Base::dx / max_speed;
        ZIRAN_INFO("Computed next dt (based on CFL): ", dt_compute);
        ZIRAN_INFO("Computed dx (based on CFL): ", Base::dx, max_speed,
                   Base::cfl);
        ZIRAN_INFO("Fluid resident CFL reduction: particles=", stats.particles,
                   " reduction_ms=", stats.reduction_ms);
        return dt_compute;
      }
      GPU_STAGE3A::SolidParticleReductionStats solid_stats;
      if (reduceResidentSolidParticleState(solid_stats)) {
        const TV p_min_corner(static_cast<T>(solid_stats.min_corner.x),
                              static_cast<T>(solid_stats.min_corner.y),
                              static_cast<T>(solid_stats.min_corner.z));
        const TV p_max_corner(static_cast<T>(solid_stats.max_corner.x),
                              static_cast<T>(solid_stats.max_corner.y),
                              static_cast<T>(solid_stats.max_corner.z));
        ZIRAN_INFO("Particle Min Corner: ", p_min_corner.transpose());
        ZIRAN_INFO("Particle Max Corner: ", p_max_corner.transpose());
        ZIRAN_INFO("Maximum particle speed: ", solid_stats.max_speed);
        double dt_compute = Base::step.max_dt;
        if (solid_stats.max_speed != 0.0)
          dt_compute = Base::cfl * Base::dx / solid_stats.max_speed;
        ZIRAN_INFO("Computed next dt (based on CFL): ", dt_compute);
        ZIRAN_INFO("Computed dx (based on CFL): ", Base::dx,
                   solid_stats.max_speed, Base::cfl);
        ZIRAN_INFO("Solid resident CFL reduction: particles=",
                   solid_stats.particles, " reduction_ms=",
                   solid_stats.reduction_ms);
        return dt_compute;
      }
    }
#endif
    return Base::calculateDt();
  }

  void gridToParticles(double dt) override {
    const bool resident_fluid_q1_g2p =
        category == MATERIAL_PHASE_FLUID && fluid_Q1Q0 &&
        gpu_prebuilt_velocity_valid &&
        gpu_velocity_transfer_device.x != nullptr &&
        gpu_velocity_transfer_device.v != nullptr &&
        gpu_velocity_transfer_device.grad_v != nullptr &&
        gpu_velocity_transfer_device.pressure != nullptr &&
        gpu_velocity_transfer_device.size ==
            static_cast<std::size_t>(particles.count);
    const bool resident_solid_q2_g2p =
        category == MATERIAL_PHASE_SOLID && gpu_solid_device_resident &&
        gpu_solid_particle_g2p_ready &&
        std::getenv("ZIRAN_GPU_SOLID_PARTICLE_OWNER_ORACLE") == nullptr;
    if (gpu_full_pipeline_strict) {
      if (category == MATERIAL_PHASE_FLUID && particles.count != 0) {
        ZIRAN_ASSERT(resident_fluid_q1_g2p,
            "strict full-GPU fluid G2P fell back to CPU");
      } else if (category == MATERIAL_PHASE_SOLID) {
        ZIRAN_ASSERT(resident_solid_q2_g2p,
            "strict full-GPU solid G2P fell back to CPU");
      }
    }
    if (!resident_fluid_q1_g2p && !resident_solid_q2_g2p)
      Base::gridToParticles(dt);
    else if (resident_fluid_q1_g2p)
      ZIRAN_INFO("Bypassing legacy fluid G2P: resident Q1 output=1");
    else
      ZIRAN_INFO("Bypassing legacy solid G2P: resident Q2 output=1");

    if (category == MATERIAL_PHASE_SOLID) {
      if (resident_solid_q2_g2p) {
        gpu_solid_host_current_x_valid = false;
        gpu_solid_host_dynamic_state_valid = false;
        gpu_solid_particle_g2p_ready = false;
        return;
      }
      auto *F_pointer =
          particles.DataManager::getPointer(F_name<T, dim>()); // 在g2p中更新F
      auto *J_pointer = particles.DataManager::getPointer(J_name<T>());
      auto *vol_pointer =
          particles.DataManager::getPointer(element_measure_name<T>());
      // `override_J` is populated by constructVelocityFromSolvedP() after a
      // coupling pressure solve.  A scene may intentionally have no fluid
      // phase for its first frames, in which case CouplingSimulation skips
      // that solve and the solid must retain its ordinary det(F) update.
      const bool has_coupling_pressure_override =
          solid_Q2Q0 && use_vp &&
          override_J.size() == static_cast<std::size_t>(particles.count);
      for (int i = 0; i < particles.count; ++i) {
        // (*J_pointer)[i] = -p / (*j_model)[i].lambda + 1;
        //让J变得有点奇怪
        (*J_pointer)[i] = (*F_pointer)[i].determinant();
        if (has_coupling_pressure_override) {
        //   (*J_pointer)[i] = (*F_pointer)[i].determinant();
          (*J_pointer)[i] = override_J[i];
        }
        MATH_TOOLS::clamp((*J_pointer)[i], (T)0.3, (T)3);
      }

      // 将g2p后interface上的速度打印到粒子上
      vis_interface_vel.resize(interface_GQ.size());
      tbb::parallel_for(0, (int)interface_GQ.size(), [&](int i) {
        TV Xp = (category == MATERIAL_PHASE_SOLID &&
                 Base::config_scheme != CONFIG_UPDATE_LAGRANGIAN)
                    ? interface_rest_GQ[i]
                    : interface_GQ[i];
        // TV Xp = interface_GQ[i];
        TV normal = interface_N[i];
        TV picV = TV::Zero();
        // BSplineWeights<T, dim, 1> spline(Xp, Base::dx);
        BSplineWeights<T, dim, 2> spline(Xp, Base::dx);
        uint64_t offset =
            Base::SparseMask::Linear_Offset(to_std_array(spline.base_node));
        Base::grid.iterateKernel(
            spline, offset, [&](IV node, T w, TV dw, GridState<T, dim> &g) {
              picV += w * g.new_v;
            });
        vis_interface_vel[i] = (picV.transpose() * normal) * normal;
      });

      if (gpu_solid_particle_g2p_ready) {
        if (std::getenv("ZIRAN_GPU_SOLID_PARTICLE_OWNER_ORACLE")) {
          GPU_STAGE3A::SolidParticleStateInput3D device_state;
          GPU_STAGE3A::copyPersistentSolidParticleStateToHost(
              gpu_solid_particle_state, device_state);
          auto *X0_pointer =
              particles.DataManager::getPointer(X0_name<TV>());
          auto *C_pointer = particles.DataManager::getPointer(C_name<TM>());
          ZIRAN_ASSERT(X0_pointer && C_pointer &&
                           device_state.current_x.size() ==
                               static_cast<std::size_t>(particles.count),
                       "solid particle owner oracle input mismatch");
          double max_x = 0.0, max_v = 0.0, max_c = 0.0;
          double max_grad = 0.0, max_f = 0.0, max_j = 0.0;
          for (int i = 0; i < particles.count; ++i) {
            const std::size_t p = static_cast<std::size_t>(i);
            const double dx_values[3] = {
                static_cast<double>((*X0_pointer)[i][0]) -
                    device_state.current_x[p].x,
                static_cast<double>((*X0_pointer)[i][1]) -
                    device_state.current_x[p].y,
                static_cast<double>((*X0_pointer)[i][2]) -
                    device_state.current_x[p].z};
            const double dv_values[3] = {
                static_cast<double>(particles.V.array[i][0]) -
                    device_state.velocity[p].x,
                static_cast<double>(particles.V.array[i][1]) -
                    device_state.velocity[p].y,
                static_cast<double>(particles.V.array[i][2]) -
                    device_state.velocity[p].z};
            for (int d = 0; d < 3; ++d) {
              max_x = std::max(max_x, std::abs(dx_values[d]));
              max_v = std::max(max_v, std::abs(dv_values[d]));
            }
            for (int row = 0; row < 3; ++row)
              for (int col = 0; col < 3; ++col) {
                const int entry = row * 3 + col;
                max_c = std::max(max_c, std::abs(
                    static_cast<double>((*C_pointer)[i](row, col)) -
                    device_state.affine[p].values[entry]));
                max_grad = std::max(max_grad, std::abs(
                    static_cast<double>(Base::scratch_gradV[i](row, col)) -
                    device_state.grad_velocity[p].values[entry]));
                max_f = std::max(max_f, std::abs(
                    static_cast<double>((*F_pointer)[i](row, col)) -
                    device_state.f[p].values[entry]));
              }
            max_j = std::max(max_j, std::abs(
                static_cast<double>((*J_pointer)[i]) - device_state.j[p]));
          }
          ZIRAN_INFO("GPU solid particle owner oracle: particles=",
              particles.count, " max_x=", max_x, " max_v=", max_v,
              " max_C=", max_c, " max_grad=", max_grad,
              " max_F=", max_f, " max_J=", max_j);
        }
      } else {
        GPU_STAGE3A::invalidatePersistentSolidParticleState3D(
            gpu_solid_particle_state);
        gpu_solid_p2g_node_map = {};
        gpu_solid_p2g_indices_ready = false;
        gpu_solid_legacy_q2_topology_seed.clear();
        gpu_solid_device_grid_active = false;
      }
      gpu_solid_host_current_x_valid = true;
      gpu_solid_host_dynamic_state_valid = true;
      gpu_solid_particle_g2p_ready = false;

    } else {
      auto *J_pointer = particles.DataManager::getPointer(J_name<T>());
      auto &Xarray = particles.X.array;
      auto &Varray = particles.V.array;
      const bool boundary_collision_probe =
          std::getenv("ZIRAN_FLUID_BOUNDARY_COLLISION_PROBE") != nullptr;
      const char* staggered_snap_env =
          std::getenv("ZIRAN_GPU_FLUID_STAGGERED_SNAP_EPS");
      const double staggered_snap_epsilon = staggered_snap_env
          ? std::strtod(staggered_snap_env, nullptr) : 0.0;
#ifdef ENABLE_CUDA_STAGE2_PROBE
      const bool resident_boundary_projection =
          gpu_fluid_device_resident && gpu_velocity_transfer_device_x_valid &&
          gpu_velocity_transfer_device_v_grad_valid &&
          gpu_velocity_transfer_device.size ==
              static_cast<std::size_t>(particles.count) &&
          staggered_snap_epsilon <= 0.0 &&
          (gpu_box_shell_collision.valid ||
           Base::collision_objects.empty());
      if constexpr (dim == 3) {
        if (resident_boundary_projection) {
          GPU_STAGE2::FluidBoundaryProjectionStats stats;
          GPU_STAGE2::projectFluidBoundaryCollision3D(
              gpu_velocity_transfer, gpu_box_shell_collision,
              static_cast<double>(Base::dx), &stats);
          gpu_velocity_transfer_host_x_valid = false;
          gpu_velocity_transfer_host_v_valid = false;
          if (boundary_collision_probe || stats.projected_particles != 0)
            ZIRAN_INFO("GPU fluid boundary projection: particles=",
                       stats.particles, " projected=",
                       stats.projected_particles, " threshold=",
                       -3 * Base::dx, " projection_ms=",
                       stats.projection_ms);
          return;
        }
      }
#endif
      if (gpu_full_pipeline_strict && particles.count != 0) {
        ZIRAN_ASSERT(false,
            "strict full-GPU fluid boundary projection fell back to CPU");
      }
      std::atomic<int> boundary_projection_count{0};
      std::atomic<int> boundary_zero_velocity_count{0};
      std::atomic<int> staggered_snap_count{0};
      std::atomic<bool> particle_x_changed_after_device_g2p{false};
#ifdef ENABLE_CUDA_STAGE2_PROBE
      const bool patch_resident_v_grad =
          gpu_velocity_transfer_device_v_grad_valid &&
          gpu_velocity_transfer_device.v != nullptr &&
          gpu_velocity_transfer_device.grad_v != nullptr &&
          gpu_velocity_transfer_device.size ==
              static_cast<std::size_t>(particles.count);
      // A boundary hit below rewrites both X and V (never just V). Patching
      // X in place keeps the resident owner valid across the hit instead of
      // invalidating it for the whole substep, so PositionCorrector's own
      // GPU pushout (which needs resident X) still has a fast path even on
      // substeps with a handful of boundary hits.
      const bool patch_resident_position =
          patch_resident_v_grad && gpu_velocity_transfer_device_x_valid &&
          gpu_velocity_transfer_device.x != nullptr;
#else
      const bool patch_resident_v_grad = false;
      const bool patch_resident_position = false;
#endif
      std::vector<unsigned char> resident_v_grad_patch_flags(
          patch_resident_v_grad ? static_cast<std::size_t>(particles.count) : 0,
          0);
      tbb::parallel_for(0, (int)particles.count, [&](int i) {
        if (fluid_Q1Q0) {
          Xarray[i] = override_X[i];
          Varray[i] = override_V[i];
          if (gpu_velocity_transfer_host_grad_v_valid)
            Base::scratch_gradV[i] = override_gradVp[i];
          if (gpu_velocity_transfer_device.pressure == nullptr ||
              gpu_velocity_transfer_host_pressure_valid) {
            ZIRAN_ASSERT(override_J.size() ==
                    static_cast<std::size_t>(particles.count),
                "fluid host pressure override is incomplete");
            (*J_pointer)[i] = override_J[i];
          }
        }
        // Q1 uses floor((X - 0.5 dx) / dx).  The CPU P2G order and the
        // parallel GPU reduction differ only at round-off level, but a
        // particle that mathematically lies on this staggered plane may then
        // enter opposite cells on the next substep and cause a discontinuous
        // analytical-quadrature rebuild.  Keep this opt-in while validating
        // the compatibility policy; it only moves exact tie cases by epsilon
        // grid units, not ordinary particle motion.
        if (gpu_prebuilt_velocity_valid && staggered_snap_epsilon > 0.0) {
          for (int d = 0; d < dim; ++d) {
            const double q = (static_cast<double>(Xarray[i][d]) -
                              0.5 * static_cast<double>(Base::dx)) /
                static_cast<double>(Base::dx);
            const double nearest = std::round(q);
            if (std::abs(q - nearest) <= staggered_snap_epsilon) {
              Xarray[i][d] = static_cast<T>((nearest + 0.5) * Base::dx);
              ++staggered_snap_count;
              particle_x_changed_after_device_g2p.store(
                  true, std::memory_order_relaxed);
            }
          }
        }
        for (size_t k = 0; k < Base::collision_objects.size(); k++) {
          T phi;
          TV n;
          if (Base::collision_objects[k]->queryInside(Xarray[i], phi, n,
                                                      -3 * Base::dx)) {
            if (boundary_collision_probe)
              ++boundary_projection_count;
            Xarray[i] -= (phi + 2 * Base::dx) * n;
            Varray[i] = TV::Zero();
            if (patch_resident_v_grad)
              resident_v_grad_patch_flags[static_cast<std::size_t>(i)] = 1;
            // When the resident X owner can be sparsely patched below, keep
            // it valid instead of invalidating the whole substep's device
            // position field.
            if (!patch_resident_position)
              particle_x_changed_after_device_g2p.store(
                  true, std::memory_order_relaxed);
            if (boundary_collision_probe)
              ++boundary_zero_velocity_count;
          }
        }
      });
#ifdef ENABLE_CUDA_STAGE2_PROBE
      if constexpr (dim == 3) if (patch_resident_v_grad) {
        std::vector<int> patch_indices;
        std::vector<GPU_STAGE2::Vec3d> patch_velocity;
        std::vector<GPU_STAGE2::Mat3d> patch_grad_velocity;
        std::vector<GPU_STAGE2::Vec3d> patch_position;
        for (int i = 0; i < particles.count; ++i) {
          if (!resident_v_grad_patch_flags[static_cast<std::size_t>(i)])
            continue;
          patch_indices.push_back(i);
          const TV& v = Varray[i];
          patch_velocity.push_back(GPU_STAGE2::Vec3d{
              static_cast<double>(v[0]), static_cast<double>(v[1]),
              static_cast<double>(v[2])});
          if (gpu_velocity_transfer_host_grad_v_valid) {
            GPU_STAGE2::Mat3d grad;
            for (int col = 0; col < 3; ++col)
              for (int row = 0; row < 3; ++row)
                grad.values[row + 3 * col] = static_cast<double>(
                    Base::scratch_gradV[i](row, col));
            patch_grad_velocity.push_back(grad);
          }
          if (patch_resident_position) {
            const TV& x = Xarray[i];
            patch_position.push_back(GPU_STAGE2::Vec3d{
                static_cast<double>(x[0]), static_cast<double>(x[1]),
                static_cast<double>(x[2])});
          }
        }
        if (!patch_indices.empty()) {
          GPU_STAGE2::VelocityTransferPatchStats patch_stats;
          GPU_STAGE2::patchFluidVelocityTransferParticles3D(
              gpu_velocity_transfer, patch_indices, patch_velocity,
              patch_grad_velocity, &patch_stats, patch_position);
          ZIRAN_INFO("GPU fluid boundary V/X/gradV patch: particles=",
              patch_stats.particles, " resident_x=",
              patch_resident_position ? 1 : 0,
              " upload_ms=", patch_stats.upload_ms,
              " patch_ms=", patch_stats.patch_ms,
              " total_ms=", patch_stats.total_ms);
        }
      }
#endif
      if (boundary_collision_probe)
        ZIRAN_INFO("fluid boundary projection: particles=", particles.count,
                   " projected=", boundary_projection_count.load(),
                   " zeroed_velocity=", boundary_zero_velocity_count.load(),
                   " threshold=", -3 * Base::dx);
      if (staggered_snap_epsilon > 0.0)
        ZIRAN_INFO("GPU fluid staggered-grid tie snap: epsilon=",
                   staggered_snap_epsilon, " snapped=",
                   staggered_snap_count.load());
      if (particle_x_changed_after_device_g2p.load(
              std::memory_order_relaxed))
        gpu_velocity_transfer_device_x_valid = false;
      gpu_velocity_transfer_host_x_valid = true;
      gpu_velocity_transfer_host_v_valid = true;
    }
  }

